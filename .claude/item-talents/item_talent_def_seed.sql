-- и DESIGN.md разделу «Роллы перков и качество» — меню рядов 1-2 расширены
-- (8 и 9 вариантов на пул соответственно, у пула E +1 доп. вариант в каждом
-- ряду: «Крепость щита» в ряду 1, «Стена» в ряду 2), ряд 3 стал ЕДИНЫМ для
-- всех пулов (кроме E, где вместо «Легкости» — «Стойкость»). Предмет при
-- получении роллит только 3 варианта из choice-меню на ряд (хранится в
-- acore_characters.item_talent_rolls, см. mod_item_talents_rolls.sql) —
-- выбор в игре остаётся «1 из 3». Ряд 4 не менялся (общий для всех пулов).

CREATE TABLE IF NOT EXISTS `item_talent_def` (
  `pool`     CHAR(1)      NOT NULL,  -- A ткань, B кожа, C кольчуга, D латы,
                                     -- E щит, F ближний бой, G дальний, H кастерское
  `row`      TINYINT      NOT NULL,  -- 1..5
  `choice`   TINYINT      NOT NULL,  -- id варианта в меню ряда (не то же самое,
                                     -- что слот 1..3, который реально роллится)
  `name_ru`  VARCHAR(64)  NOT NULL,
  `desc_ru`  VARCHAR(255) NOT NULL,  -- {N} подставляется модулем
  `effect`   VARCHAR(32)  NOT NULL,
  `base`     FLOAT NOT NULL DEFAULT 0,
  `per_ilvl` FLOAT NOT NULL DEFAULT 0,
  PRIMARY KEY (`pool`,`row`,`choice`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

