# -*- coding: utf-8 -*-
"""PNG -> TGA (32bpp, без сжатия, origin внизу) для чертежей предмета.

Клиент не читает PNG и требует стороны, кратные степени двойки, поэтому арты
1774x887 (ровно 2:1) ужимаются в 1024x512 - про размер см. комментарий у W/H.

По краям кладётся альфа-растушёвка, и вот зачем. Нарисованный в скине меч из
листа вырезан, но вырезан НЕ ВПРИТЫК: по периметру оставлена полоска
оригинала, иначе пропадали скруглённые углы листа и его собственная затенённая
кромка. Чертёж кладётся на лист целиком и своими полупрозрачными краями
смешивается с этой полоской - шва не видно, а углы остаются на месте.

Ширина фейда подобрана под ширину оставленной полоски (20 точек арта - это
примерно 3 % по ширине и 6 % по высоте) с запасом на плавность.

Исходники (sword.png, axe_2h.png и прочие, 1774x887) лежат у владельца в
папке загрузок и в репозиторий не копируются - 17 МБ ради одноразовой
конвертации. Путь к ним передаётся аргументом.

Запуск:
    python png2tga.py <исходный.png> <результат.tga>
"""
import sys
from PIL import Image

# 1024x512, а не 512x256. Окно занимает 768x512 условных единиц интерфейса, но
# на экране единица больше единицы: при 1080p на UI-единицу приходится 1.4
# точки, и лист шириной 465 единиц растягивается до ~654 настоящих точек.
# Текстура 512 в такой лист УВЕЛИЧИВАЛАСЬ и мылила; 1024 в него ужимается и
# остаётся резкой.
W, H = 1024, 512
FADE_X, FADE_Y = 0.030, 0.060      # доля стороны, уходящая в прозрачность


def convert(src, dst):
    img = Image.open(src).convert('RGBA').resize((W, H), Image.LANCZOS)
    px = img.load()

    fade_x = max(1.0, FADE_X * W)
    fade_y = max(1.0, FADE_Y * H)

    for y in range(H):
        dy = min(y, H - 1 - y)
        fy = 1.0 if dy >= fade_y else dy / fade_y
        for x in range(W):
            dx = min(x, W - 1 - x)
            fx = 1.0 if dx >= fade_x else dx / fade_x
            a = fx * fy
            if a < 1.0:
                # Плавность вместо линейного спада: smoothstep убирает видимую
                # границу там, где фейд только начинается.
                sm = a * a * (3.0 - 2.0 * a)
                r, g, b, _ = px[x, y]
                px[x, y] = (r, g, b, int(round(255.0 * sm)))

    header = bytes([0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0, 0,
                    W & 0xFF, (W >> 8) & 0xFF,
                    H & 0xFF, (H >> 8) & 0xFF,
                    32, 8])          # 32 бита на пиксель, 8 бит альфы, origin внизу
    body = bytearray()
    for y in range(H - 1, -1, -1):
        for x in range(W):
            r, g, b, a = px[x, y]
            body += bytes((b, g, r, a))

    with open(dst, 'wb') as f:
        f.write(header)
        f.write(body)
    print('%s -> %s (%dx%d, %d байт)'
          % (src, dst, W, H, len(header) + len(body)))


if __name__ == '__main__':
    convert(sys.argv[1], sys.argv[2])
