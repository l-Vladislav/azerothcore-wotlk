# -*- coding: utf-8 -*-
"""Нарезка скина окна верстака (frame_3.png) на фон и отдельные компоненты.

Клиент 3.3.5 не читает PNG и требует стороны, кратные степени двойки, поэтому
всё уезжает в TGA 32bpp с origin внизу.

Что делает скрипт:

1. ФОН. Нутро левой панели СТИРАЕТСЯ целиком - и полоса вкладок, и девять
   плашек списка, и планка между ними: их число и размер теперь задаёт не
   художник, а сервер (типов оружия десять, а слотов в арте шесть; список
   нужен со скроллом). На их месте лежит одна каменная плита, собранная из
   панели итога справа, - от рамы до рамы, без внутренних бордюров. Медальон
   возвращается поверх неё, чтобы камень уходил ему под шипы. Остальное - рама,
   чертёжная панель, углы - остаётся как есть. Результат режется на шесть
   плиток 512x512 (окно показывается вдвое меньше).

2. КОМПОНЕНТЫ. Вырезаются кнопки: пустое гнездо вкладки (иконка внутри
   замазана фоном самого гнезда), золотое активное гнездо, плашка строки
   списка, красный крестик и нижняя золотая кнопка. Каждый кусок кладётся в
   холст со сторонами степени двойки, а координаты видимой части печатаются
   как готовая таблица TexCoord для Lua.
"""
import os
from PIL import Image, ImageFilter

# Исходник лежит рядом со скриптом: нарезка должна повторяться из репозитория,
# а не из чьей-то папки загрузок.
SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'frame_3.png')
DST = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   '..', '..', 'modules', 'mod-advanced-professions',
                   'ClientAddon', 'AdvProfUI', 'textures')
DST = os.path.normpath(DST)

# --- прямоугольники, снятые с арта (координаты в пикселях frame_3.png) -------
#
# Полоса кнопок стала ДВУХРЯДНОЙ, и под неё пришлось занять место сверху
# списка. Разделительная планка между полосой и списком в арте нарисована
# один раз, поэтому её не стираем, а ПЕРЕНОСИМ: вырезаем с исходного места и
# кладём ниже, под второй ряд кнопок. Иначе её пришлось бы дорисовывать.
# Левая панель стала ОДНОЙ каменной плитой во всю внутреннюю площадь: и полоса
# вкладок, и девять плашек списка, и разделительная планка между ними, и
# коричневые поля по краям (решение владельца 2026-08-29). Раньше это были две
# отдельные заплаты с планкой на стыке, и каждый их край читался как лишний
# бордюр - слева, снизу и сверху под медальоном.
# Верх коробки - НЕ по верхней планке рамы, а под внутренним карнизом (он идёт
# на 150-165 и кончается справа скошенным углом): срезав его, плита оставляла
# от угла висеть чёрный клин.
ERASE_PANEL = (42, 165, 494, 966)    # нутро левой панели целиком

# В нутро панели свисают два куска рамы: сверху слева - нижние шипы медальона,
# снизу слева - паутина углового орнамента. Камень кладём ПОД них: сначала плита
# на весь прямоугольник, потом на эти места возвращается исходный арт - но
# только там, где он не кожа (см. not_leather).
# Низ куска угла начинается НИЖЕ золотой стойки списка (889-899): её тёмная
# кромка - тоже «не кожа», и от края куска на камне оставалась тонкая черта.
RESTORE = [
    (42, 165, 205, 204),          # нижние шипы медальона
    (42, 902, 190, 962),          # луч углового орнамента, уходящий в панель
]

# Нарисованный на листе меч тоже СТИРАЕТСЯ. Художник вклеил сюда готовый
# чертёж (sword.png) - тот же файл, что лежит в textures/item-sword.tga, с
# собственным пергаментом и уголками. Аддон кладёт такой чертёж на это место
# сам, по выбранному типу оружия, поэтому вклеенный меч мешает: под кинжалом
# или щитом он просвечивал бы по краям.
# Вырезаем НЕ ВПРИТЫК: по периметру остаётся полоска в 12 точек. Без неё
# пропадали скруглённые углы листа и его затенённая кромка, а лист превращался
# в плоский прямоугольник. Чертёж кладётся поверх целиком и смешивается с этой
# полоской своими полупрозрачными краями (растушёвку делает png2tga.py).
ERASE_SHEET = (558, 198, 1447, 569)  # лист без крайних 20 точек
SRC_PAPER = (960, 245, 1220, 305)    # чистый пергамент: найден перебором, без штрихов

# Полосу типов кладём на ТЁМНЫЙ КАМЕНЬ - тот же, что на панели итога справа
# (решение владельца 2026-08-29). Кожей она смотрелась пятном: гнёзда и сами
# тёмные, и светло-коричневый фон между ними разваливал ряд. Кусок берётся
# ровно по размеру полосы (445x184), поэтому повтора нет вовсе - только он и
# избавляет от полос, которые давало зеркальное замощение кожи.
SRC_STONE_BOX = (556, 613, 1444, 873)  # вся чистая площадь панели итога

CUTS = {
    'slot':        (418, 213, 488, 285),   # гнездо вкладки (иконку затрём)
    'slot-active': (47, 213, 117, 289),    # золотое активное гнездо
    'row':         (65, 311, 467, 363),   # плашка строки списка
    'btn-close':   (1422, 58, 1496, 126),  # красный крестик
    'btn':         (1158, 894, 1478, 988), # нижняя золотая кнопка
    'rail':        (62, 288, 478, 300),  # планка-разделитель под полосой
}

# Гнёзда отдаём с затёртой серединой: иконку внутрь кладёт уже аддон.
# Вырез гнезда обрезан вплотную по металлу: вокруг него в арте лежит чёрный
# зазор между соседними гнёздами, и на камне он читался чёрной окантовкой у
# каждой кнопки типа. Отступ затирки уменьшен на столько же, на сколько ужался
# вырез, - иначе затирка съела бы саму рамку.
WIPE_INSIDE = {'slot': 8, 'slot-active': 12}

# У активного гнезда снизу висит золотой язычок, и вырез приходится вести ниже
# рамки: обрезать по ней - значит отрубить язычок посередине. Но по бокам от
# язычка в арте чёрный фон, и на камне под выбранной кнопкой висела бы чёрная
# полка. Поэтому ниже рамки альфа задаётся яркостью: язычок остаётся, фон вокруг
# него уходит в прозрачность. Числа - (с какой строки, порог, размах).
TAIL_FADE = {'slot-active': (72, 8, 32)}

# В планку-разделитель попадают два следа от её прежних соседей: слева золотой
# низ активной вкладки, справа рыжая точка от стойки списка. На новом месте оба
# висели бы непонятными блямбами, поэтому закрываем их зеркалом соседнего куска
# самой планки: (откуда взять, докуда, куда положить).
MIRROR_NUB = {'rail': [(63, 126, 0), (395, 405, 405)]}

# Кнопка в арте - шестиугольная плашка на тёмной каменной планке, и прямоугольный
# вырез забирает планку вместе с ней. Пока кнопка активна, этого не видно: кусок
# ложится ровно на своё нарисованное место. Но выключенная кнопка гасится
# SetVertexColor, а подсветка наведения складывается через ADD - и то и другое
# красит ВЕСЬ кусок, из-за чего вокруг кнопки появлялся тёмный квадрат.
# Поэтому всё, что вне плашки, обнуляем по альфе.
#
# Границы сняты с арта построчно: сверху и снизу плашка идёт ровно
# (x 32..285 при y 10..82), а по бокам срезана под 45 градусов - к середине
# (y 46) она расширяется на 29 точек в каждую сторону.
MASK_HEX = {
    'btn': dict(top=9, bottom=83, left=31, right=286, mid=46, chamfer=29),
}


def pot(n):
    p = 1
    while p < n:
        p *= 2
    return p


def write_tga(img, path):
    """TGA 32bpp без сжатия, origin внизу - единственный формат, который
    3.3.5 читает без плясок."""
    w, h = img.size
    px = img.load()
    header = bytes([0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0, 0,
                    w & 0xFF, (w >> 8) & 0xFF,
                    h & 0xFF, (h >> 8) & 0xFF,
                    32, 8])
    body = bytearray()
    for y in range(h - 1, -1, -1):
        for x in range(w):
            r, g, b, a = px[x, y]
            body += bytes((b, g, r, a))
    with open(path, 'wb') as f:
        f.write(header)
        f.write(body)
    return len(header) + len(body)




def feather_fill(base, box, patch, soft=14, blur=2.0):
    """Замазать box повтором patch, растворив края заплаты в оригинале.

    Нужна там, где у замазываемого места есть собственная кромка: у листа
    чертежа затенённые края и скруглённые углы, и ровная заливка обрывалась об
    них прямой линией. Маска гасит заплату на `soft` точках по периметру, и
    стыка не видно вовсе."""
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    pw, ph = patch.size

    region = Image.new('RGBA', (w, h))
    for oy in range(0, h, ph):
        for ox in range(0, w, pw):
            piece = patch
            if (ox // pw) % 2:
                piece = piece.transpose(Image.FLIP_LEFT_RIGHT)
            if (oy // ph) % 2:
                piece = piece.transpose(Image.FLIP_TOP_BOTTOM)
            region.paste(piece, (ox, oy))
    if blur:
        region = region.filter(ImageFilter.GaussianBlur(blur))

    mask = Image.new('L', (w, h), 255)
    mp = mask.load()
    for y in range(h):
        dy = min(y, h - 1 - y)
        for x in range(w):
            d = min(x, w - 1 - x, dy)
            if d < soft:
                t = d / float(soft)
                mp[x, y] = int(255 * t * t * (3.0 - 2.0 * t))
    base.paste(region, (x0, y0), mask)


def tail_fade(img, row, low, span):
    """Ниже строки `row` сделать альфу пропорциональной яркости.

    Годится там, где из куска торчит светлая деталь на чёрном фоне: обводить её
    руками не нужно, порог отделяет металл от пустоты сам."""
    w, h = img.size
    px = img.load()
    for y in range(max(0, row), h):
        for x in range(w):
            r, g, b, a = px[x, y]
            lum = (r * 299 + g * 587 + b * 114) // 1000
            t = (lum - low) / float(span)
            t = 0.0 if t < 0.0 else (1.0 if t > 1.0 else t)
            px[x, y] = (r, g, b, int(a * t))


def wipe_inside(img, border):
    """Затереть середину гнезда его же фоном: нарисованную иконку убираем,
    металлическую рамку оставляем. Цвет берём из углов внутренней части -
    там иконки нет."""
    w, h = img.size
    px = img.load()

    def avg(bx, by):
        acc = [0, 0, 0, 0]
        n = 0
        for y in range(by, by + 7):
            for x in range(bx, bx + 7):
                p = px[x, y]
                for i in range(4):
                    acc[i] += p[i]
                n += 1
        return [c // n for c in acc]

    top = avg(border + 2, border + 2)
    bot = avg(border + 2, h - border - 9)
    inner = (border, border, w - border, h - border)
    for y in range(inner[1], inner[3]):
        t = (y - inner[1]) / float(max(1, inner[3] - inner[1] - 1))
        col = tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(4))
        for x in range(inner[0], inner[2]):
            px[x, y] = col


def mask_hex(img, top, bottom, left, right, mid, chamfer, soft=1.2):
    """Оставить непрозрачной только шестиугольную плашку кнопки.

    Края растушёвываем на точку: под куском лежит тот же самый рисунок из
    фона, поэтому мягкая кромка не даёт ступеньки, а ровный обрез дал бы."""
    w, h = img.size
    mask = Image.new('L', (w, h), 0)
    mp = mask.load()
    for y in range(max(0, top), min(h, bottom + 1)):
        inset = max(0, chamfer - abs(y - mid))
        x0 = max(0, left - inset)
        x1 = min(w - 1, right + inset)
        for x in range(x0, x1 + 1):
            mp[x, y] = 255
    if soft:
        mask = mask.filter(ImageFilter.GaussianBlur(soft))

    px = img.load()
    mpx = mask.load()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            px[x, y] = (r, g, b, a * mpx[x, y] // 255)


def stone_slab(art, w, h, fade=32):
    """Собрать каменную плиту нужного размера из панели итога.

    Чистого камня в арте 888x260, а нутро левой панели почти восемьсот точек в
    высоту. Зеркальный повтор одного куска давал бы узнаваемую сетку трещин,
    поэтому ряды берутся с РАЗНЫХ мест панели и через раз отражаются, а стыки
    гасятся перекрёстным затуханием в `fade` точек - шва не остаётся, и текстура
    при этом не размывается, как было бы от общего блюра."""
    x0, y0, x1, y1 = SRC_STONE_BOX
    src_w, src_h = x1 - x0, y1 - y0
    span = min(w, src_w)

    def tile(n):
        # Смещение по горизонтали разводит трещины: у соседних рядов они разные.
        off = (n * 197) % max(1, src_w - span)
        piece = art.crop((x0 + off, y0, x0 + off + span, y1))
        if n % 2:
            piece = piece.transpose(Image.FLIP_LEFT_RIGHT)
        if (n // 2) % 2:
            piece = piece.transpose(Image.FLIP_TOP_BOTTOM)
        if span < w:
            wide = Image.new('RGBA', (w, src_h))
            for ox in range(0, w, span):
                wide.paste(piece, (ox, 0))
            piece = wide
        return piece

    slab = Image.new('RGBA', (w, h))
    step = src_h - fade
    n = 0
    y = 0
    while y < h:
        piece = tile(n)
        if n == 0:
            slab.paste(piece, (0, 0))
        else:
            mask = Image.new('L', (w, src_h), 255)
            mp = mask.load()
            for my in range(fade):
                v = int(255 * my / float(fade))
                for mx in range(w):
                    mp[mx, my] = v
            slab.paste(piece, (0, y), mask)
        y += step
        n += 1
    return slab


def not_leather(img):
    """Маска «здесь не кожа»: по ней рама возвращается поверх камня.

    Кожа панели - насыщенный коричневый, и в тени она уходит почти в чёрный;
    металл орнамента обесцвечен, а золото заметно светлее. Порог по яркости
    поэтому низкий, а по насыщенности - только снизу: первый вариант резал
    насыщенность и сверху, из-за чего кожа в глубокой тени (sat под единицу)
    считалась орнаментом и возвращалась на камень квадратом по границе куска."""
    w, h = img.size
    px = img.load()
    mask = Image.new('L', (w, h))
    mp = mask.load()
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y][:3]
            hi, lo = max(r, g, b), min(r, g, b)
            sat = 0.0 if hi == 0 else (hi - lo) / float(hi)
            val = hi / 255.0
            hue = 0.0
            if hi != lo:
                d = float(hi - lo)
                if hi == r:
                    hue = ((g - b) / d) % 6
                elif hi == g:
                    hue = (b - r) / d + 2
                else:
                    hue = (r - g) / d + 4
                hue *= 60
            leather = 8 <= hue <= 45 and sat >= 0.40 and val <= 0.32
            mp[x, y] = 0 if leather else 255
    # Тёмное золото кольца попадает в тот же угол цветового круга, что и кожа, и
    # в маске от него остаются дырки. Замыкание (расширить - сжать) их
    # затягивает, не трогая внешнюю границу орнамента, а медиана добирает
    # одиночные точки: без неё по краю остаётся коричневая крупа.
    mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.MinFilter(5))
    return mask.filter(ImageFilter.MedianFilter(3))


def main():
    art = Image.open(SRC).convert('RGBA')

    # --- 1. фон ---
    bg = art.copy()
    x0, y0, x1, y1 = ERASE_PANEL
    slab = stone_slab(art, x1 - x0, y1 - y0)
    feather_fill(bg, ERASE_PANEL, slab, soft=8, blur=0)
    # Медальон возвращается ПОВЕРХ плиты: камень должен уходить ему под шипы, а
    # не обрываться перед ними коричневой ступенькой.
    for box in RESTORE:
        piece = art.crop(box)
        bg.paste(piece, (box[0], box[1]), not_leather(piece))
    feather_fill(bg, ERASE_SHEET, art.crop(SRC_PAPER))
    bg.save(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         'preview-bg.png'))

    half = bg.resize((1536, 1024), Image.LANCZOS)
    for row in range(2):
        for col in range(3):
            tile = half.crop((col * 512, row * 512, col * 512 + 512,
                              row * 512 + 512))
            name = 'frame-%d-%d.tga' % (row + 1, col + 1)
            size = write_tga(tile, os.path.join(DST, name))
            print('%-18s 512x512  %d байт' % (name, size))

    # --- 2. компоненты ---
    coords = []
    for name, box in CUTS.items():
        piece = art.crop(box)
        if name in WIPE_INSIDE:
            wipe_inside(piece, WIPE_INSIDE[name])
        if name in TAIL_FADE:
            tail_fade(piece, *TAIL_FADE[name])
        if name in MASK_HEX:
            mask_hex(piece, **MASK_HEX[name])
        for src0, src1, dst in MIRROR_NUB.get(name, ()):
            nub = piece.crop((src0, 0, src1, piece.size[1]))
            piece.paste(nub.transpose(Image.FLIP_LEFT_RIGHT), (dst, 0))
        w, h = piece.size
        cw, ch = pot(w), pot(h)
        canvas = Image.new('RGBA', (cw, ch), (0, 0, 0, 0))
        canvas.paste(piece, (0, 0))
        write_tga(canvas, os.path.join(DST, name + '.tga'))
        coords.append((name, w, h, cw, ch))
        print('%-18s %dx%d в холсте %dx%d' % (name + '.tga', w, h, cw, ch))
        piece.save(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                'preview-%s.png' % name))

    print('\n-- координаты для Lua (доля холста, занятая картинкой):')
    print('local UV = {')
    for name, w, h, cw, ch in coords:
        print('    ["%s"] = { %.6f, %.6f },   -- %dx%d' %
              (name, w / float(cw), h / float(ch), w, h))
    print('}')


if __name__ == '__main__':
    main()
