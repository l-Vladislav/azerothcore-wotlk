-- дважды разъезжались лестницы.
INSERT INTO `ap_material`
  (`entry`, `role`, `kind`, `part_kind_id`, `insert_type_id`,
   `stat_type`, `stat_value`, `ilvl_min`, `ilvl_max`,
   `quality_min`, `quality_max`, `enabled`)
SELECT o.`entry`, 'insert', dm.`kind`, 0, dm.`insert_type_id`,
       o.`stat`,
       GREATEST(1, ROUND(v.`val` * COALESCE(w.`weight`, 1.0))),
       b.`lo`, IF(b.`idx` = 12, 0, b.`hi`), 0, 0, 1
FROM `ap_own` o
