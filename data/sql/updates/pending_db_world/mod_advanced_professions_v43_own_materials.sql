LEFT JOIN `ap_stat_weight` w ON w.`stat_type` = o.`stat`;

-- --------------------------------------------------------------------------
-- 4. Добыча: там же, где донор, но реже
-- --------------------------------------------------------------------------
-- Сорок строк на камень - потолок нарочный: у аквамарина четыре с половиной
-- сотни источников, и копировать их целиком значит раздуть таблицу добычи
-- ради одного камня. Берутся самые щедрые.
INSERT IGNORE INTO `gameobject_loot_template`
  (`Entry`, `Item`, `Reference`, `Chance`, `QuestRequired`, `LootMode`,
   `GroupId`, `MinCount`, `MaxCount`, `Comment`)
SELECT `Entry`, `Item`, 0, `Chance`, 0, 1, `grp`, 1, 1, `note`
FROM (
  SELECT `Entry`, `Item`, `note`, `Chance`,
         -- В группу донора садимся, только если она не переполнится: у
         -- сгруппированного броска сумма долей не должна переваливать за сто,
         -- иначе ядро ругается в лог, а ванильные вещи теряют свои доли.
         IF(`gid` > 0 AND `total` + `Chance` <= 97, `gid`, 0) AS `grp`, `rn`
  FROM (
    SELECT gl.`Entry` AS `Entry`, o.`entry` AS `Item`,
           CONCAT('Верстак: вставка - ', o.`name`) AS `note`,
           LEAST(1.5, GREATEST(0.03, gl.`Chance` * f.`loot`)) AS `Chance`,
           gl.`GroupId` AS `gid`, COALESCE(gs.`total`, 0) AS `total`,
           -- Сорок источников на камень, и выбираются они СПЕРВА из тех,
           -- где донор лежит в группе: групповые строки скромнее по шансу, и
           -- отбор «по самому щедрому» набирал одни одиночные - копия тогда
           -- добавляла бросок вместо того, чтобы занять долю в существующем.
           ROW_NUMBER() OVER (PARTITION BY o.`entry`
                              ORDER BY (gl.`GroupId` > 0) DESC,
                                       gl.`Chance` DESC,
                                       gl.`Entry`) AS `rn`
    FROM `ap_own` o
    JOIN `ap_own_factor` f ON f.`q` = o.`q`
    JOIN `gameobject_loot_template` gl ON gl.`Item` = o.`src`
    LEFT JOIN (SELECT `Entry`, `GroupId`, SUM(`Chance`) AS `total`
               FROM `gameobject_loot_template` WHERE `GroupId` > 0
               GROUP BY `Entry`, `GroupId`) gs
           ON gs.`Entry` = gl.`Entry` AND gs.`GroupId` = gl.`GroupId`
  ) y
) x WHERE `rn` <= 40;

-- Существа своей полосы. Уровень героя для полосы берётся из `ap_ilvl_level`
-- («уровень предмета -> уровень героя»), той же таблицей пользуется раздача
-- книг (v44): полоса 65-89 приходится на героев 55-63, полоса 233-284 - на
-- восьмидесятый.
--
-- Шанс свой, а не доля донорского: наверху ванильные самоцветы почти не
-- падают, и доля от их шанса давала копии две строки по сотой доле процента.
-- Отбор существ - по хешу номера: раскидан по миру и повторяется от прогона к
-- прогону. Только обычные существа: камень ремесла не должен лежать на боссе.
DROP TEMPORARY TABLE IF EXISTS `ap_own_level`;
CREATE TEMPORARY TABLE `ap_own_level` (
  `band`   TINYINT UNSIGNED PRIMARY KEY,
  `lvl_lo` TINYINT UNSIGNED NOT NULL,
  `lvl_hi` TINYINT UNSIGNED NOT NULL
);

INSERT INTO `ap_own_level` (`band`, `lvl_lo`, `lvl_hi`)
SELECT b.`idx`,
       (SELECT MIN(l.`req_level`) FROM `ap_ilvl_level` l
        WHERE l.`ilvl_max` >= b.`lo`),
       (SELECT MIN(l.`req_level`) FROM `ap_ilvl_level` l
        WHERE l.`ilvl_max` >= b.`hi`)
FROM `ap_band` b;

INSERT IGNORE INTO `creature_loot_template`
  (`Entry`, `Item`, `Reference`, `Chance`, `QuestRequired`, `LootMode`,
   `GroupId`, `MinCount`, `MaxCount`, `Comment`)
SELECT `lootid`, `Item`, 0, `Chance`, 0, 1, 0, 1, 1, `note`
FROM (
  SELECT ct.`lootid` AS `lootid`, o.`entry` AS `Item`,
         f.`mob` AS `Chance`,
         CONCAT('Верстак: вставка - ', o.`name`) AS `note`,
         ROW_NUMBER() OVER (PARTITION BY o.`entry`
                            ORDER BY MD5(ct.`entry`)) AS `rn`
  FROM `ap_own` o
  JOIN `ap_own_factor` f ON f.`q` = o.`q`
  JOIN `ap_own_level` bl ON bl.`band` = o.`band`
  JOIN `creature_template` ct
    ON ct.`rank` = 0 AND ct.`lootid` > 0
   AND ct.`minlevel` BETWEEN bl.`lvl_lo` AND bl.`lvl_hi`
   -- Таблица добычи общая у разных существ: повесив её по одному уровню, мы
   -- ловим и низкоуровневых соседей с тем же `lootid` (замер: 81 камень из 222
   -- оказался на существах на пять с лишним уровней ниже своей полосы). Берём
   -- только те таблицы, у которых ВСЕ хозяева в границах полосы.
   AND NOT EXISTS (SELECT 1 FROM `creature_template` c2
                   WHERE c2.`lootid` = ct.`lootid`
                     AND (c2.`minlevel` + 5 < bl.`lvl_lo`
                       OR c2.`minlevel` > bl.`lvl_hi` + 5))
) x WHERE `rn` <= 40;

DROP TEMPORARY TABLE IF EXISTS `ap_own_level`;

-- --------------------------------------------------------------------------
-- 5. Проверки: пустой ответ - сходится
-- --------------------------------------------------------------------------
-- Камень без чисел, без строки предмета или без единого источника добычи - это
-- обещание, которого система не выполнит.
SELECT COUNT(*) INTO @broken
FROM `ap_material` m
LEFT JOIN `item_template` g ON g.`entry` = m.`entry`
WHERE m.`entry` BETWEEN 185000 AND 189999
  AND (g.`entry` IS NULL OR m.`stat_value` < 1 OR m.`stat_type` = 0);

SELECT COUNT(*) INTO @nodrop
FROM `ap_material` m
WHERE m.`entry` BETWEEN 185000 AND 189999
  AND NOT EXISTS (SELECT 1 FROM `creature_loot_template` c
                  WHERE c.`Item` = m.`entry`)
  AND NOT EXISTS (SELECT 1 FROM `gameobject_loot_template` gg
                  WHERE gg.`Item` = m.`entry`);

SET @chk := IF(@broken = 0 AND @nodrop = 0,
               'SELECT ''свои вставки в порядке'' AS `проверка`',
               'SELECT 1 FROM `ОШИБКА_свой_камень_без_чисел_или_без_добычи`');
PREPARE `chk` FROM @chk;
EXECUTE `chk`;
DEALLOCATE PREPARE `chk`;

