-- синего, эпических не было нигде до тория - а ступень, в которую нечего
-- вставить, сетка не заводит вовсе.
--
-- Копия обходится дёшево: у камня в `item_template` статов НЕТ, стат и
-- величина лежат в `ap_material`. Копия нужна ради имени, качества и иконки,
-- числа ей задаёт полоса - строка берётся из `ap_band_value`, той же, по
-- которой считаются ванильные камни.
--
-- Имя - приставка качества плюс имя донора, согласованная по роду: «малахит»
-- -> «Превосходный малахит» (синий) -> «Безупречный малахит» (эпический).
--
-- Дроп: копия падает ТАМ ЖЕ, ГДЕ ДОНОР, но реже. Так уровень источника
-- сходится сам собой - малахит выпадает из медной жилы, значит и превосходный
-- малахит оттуда же.
--
-- И падает она В ТОЙ ЖЕ ГРУППЕ, что донор (решение владельца 2026-09-14): у
-- сгруппированного броска жила выбирает ОДИН камень из своего списка, и наша
-- копия занимает там долю, а не добавляет отдельный бросок сверх. Ванильные
-- вещи от этого ничего не теряют - доля берётся из незанятого остатка, и
-- проверка «сумма группы плюс наша доля не больше 97» это гарантирует. Где
-- запаса нет (258 групп из 8850) или где донор лежит без группы, строка
-- остаётся своим броском, `GroupId` = 0.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.12, §2.11.

