-- --------------------------------------------------------------------------
-- 5. Какие статы в бюджет НЕ входят
-- --------------------------------------------------------------------------
-- Бюджет вещи - это сумма её статов, и до сих пор список исключений жил
-- строчкой `NOT IN (0,1,38,39,41,42,45,48)` внутри v42, повторённой двадцать
-- раз, плюс ЧЕТЫРЬМЯ сырыми суммами `stat_value1 + ... + stat_value10` внутри
-- v32. Это не придирка к стилю: сырая сумма и есть та поломка, ради которой
-- заводился `ap_stat_weight`, только этажом выше.
--
-- Как она выглядит. Лестница качества в v32 (раздел 6b) поднимает ступень до
-- «не слабее предыдущей на десятую часть» и считает планку сырой суммой -
-- вместе с силой атаки. У титанстальной булавы предыдущая ступень несла 74
-- очка статов И 213 силы атаки; планка вышла (74 + 213) * 1.10 = 315, и
-- следующая ступень получила 225 чистых очков там, где ровня игры несёт 170.
-- Арифметика сходится до единицы, и так же сходится ещё у девяти ступеней:
--
--     саронитовая булава   0 + 157 -> планка 173, стало 173 чистых
--     кобальтовая секира  38 + 116 -> планка 169, стало 169 чистых
--
-- Сила атаки и сила заклинаний - «числа другого порядка» (у посоха 893 силы
-- заклинаний против полутора сотен очков у целой рейдовой вещи). Складывать их
-- с ловкостью в одну сумму значит объявить их несравнимыми и тут же сравнить.
--
-- Проверять так: `stat_typeN NOT IN (SELECT stat_type FROM ap_stat_budget)`.
-- Список - чёрный, а не белый: стат, о котором мы не знаем (пробивание брони,
-- меткость, опыт обращения), в бюджет входит по обычной цене, и это верно -
-- Blizzard считает их очко в очко с силой.
CREATE TABLE IF NOT EXISTS `ap_stat_budget` (
  `stat_type` TINYINT UNSIGNED NOT NULL,
  `note`      VARCHAR(255) NOT NULL DEFAULT '',
  PRIMARY KEY (`stat_type`)
) COMMENT 'статы, которые в бюджет вещи не входят (v47)';
