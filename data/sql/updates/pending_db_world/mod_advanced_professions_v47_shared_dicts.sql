-- Сама формула бюджета живёт ЗДЕСЬ и больше нигде. Раньше она стояла двадцатью
-- копиями в v42 и ещё тринадцатью сырыми суммами в v32, и копии разошлись:
-- в v42 сила атаки из бюджета исключалась, в v32 - входила.
--
-- Представление, а не временная таблица: временную mysql не даёт открыть
-- дважды в одном запросе, а бюджет спрашивают и у текущей ступени, и у
-- предыдущей разом. Обращаться так:
--
--     (SELECT `total` FROM `ap_item_budget` WHERE `entry` = cur.`entry`)
--
-- Слагаемое пишется через `IF`, а НЕ через `значение * (тип NOT IN (...))`.
-- Второе считает верно в обычном запросе, но представление mysql хранит
-- разобранным и при записи теряет скобки вокруг `NOT IN`: выражение
-- превращается в `(значение * тип) NOT IN (...)`, то есть в ноль или
-- единицу, и бюджет эпической булавы выходит 5 вместо 225. Ошибка молчит -
-- представление создаётся без единого предупреждения.
CREATE OR REPLACE VIEW `ap_item_budget` AS
SELECT it.`entry` AS `entry`,
       IF(it.`stat_type1` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value1`)
     + IF(it.`stat_type2` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value2`)
     + IF(it.`stat_type3` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value3`)
     + IF(it.`stat_type4` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value4`)
     + IF(it.`stat_type5` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value5`)
     + IF(it.`stat_type6` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value6`)
     + IF(it.`stat_type7` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value7`)
     + IF(it.`stat_type8` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value8`)
     + IF(it.`stat_type9` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value9`)
     + IF(it.`stat_type10` IN (SELECT `stat_type`
                         FROM `ap_stat_budget`),
          0, it.`stat_value10`) AS `total`
FROM `item_template` it;

