-- --------------------------------------------------------------------------
-- 1. Что в игре мусор
-- --------------------------------------------------------------------------
-- Хранится РЕГУЛЯРКАМИ, а не `LIKE`: «test» обязан ловиться словом, иначе под
-- нож уходят Greatest, Latest и Contest. Слева и справа - граница не-буквы.
--
-- Проверять так: `p.name REGEXP j.pattern`. Сравнение идёт коллацией колонки,
-- то есть без учёта регистра - `TEST`, `Test` и `test` ловятся одним правилом.
--
-- СКОБКА ЗАПИСЫВАЕТСЯ ЧЕРЕЗ `CHAR(92)`, а не слэшем, и это не причуда.
-- Слоёв разбора три - файл, строковый литерал mysql, движок регулярок ICU, -
-- и сколько слэшей доедет до ICU, зависит от того, КАК файл доставлен: при
-- проверке через `docker exec ... < файл` из четырёх слэшей получался один
-- (верно), а через `scripts/ptr-sql-apply.ps1` - два (правило переставало
-- ловить хоть что-нибудь). Ошибка при этом молчит в обе стороны: с одним
-- лишним слэшем правило не ловит ничего, с одним недостающим выражение
-- читается как «первая буква P или H» и выкашивает 4090 живых вещей вместо
-- 113 заглушек.
--
-- `CHAR(92)` - это байт слэша, собранный уже ВНУТРИ mysql: ни файл, ни
-- оболочка, ни литерал до него не дотягиваются. Посиксовый способ записать
-- скобку без слэша (`[[]`) здесь не работает - ICU падает на нём с
-- «unclosed bracket expression».
