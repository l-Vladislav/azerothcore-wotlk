-- её стат встречается в клетке, и садится в эскизы намертво.
--
-- Отличить её от ограблённого самоцвета внутри mysql нельзя: рецепты ремёсел
-- живут в `Spell.dbc`, а не в мировой базе. Поэтому список ведётся руками, а
-- ищет новых `tools/audit.py` - он Spell.dbc читает и о каждой такой вставке
-- говорит вслух.
--
