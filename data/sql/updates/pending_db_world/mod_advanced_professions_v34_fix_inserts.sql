-- mod-advanced-professions: две поправки к лестнице материалов.
--
-- Обе нашлись в логе старта мира, а не глазами: модуль сам жалуется на
-- вставку, которая не даёт чисел.
--
-- 1. НОЛЬ СТАТОВ. Величина считалась как «восьмая доля уровня плюс две единицы
--    за ступень выше зелёной» (v29), и у белых реагентов низкого уровня это
--    давало РОВНО НОЛЬ: `GREATEST(2, 10/8) + (1-2)*2 = 0`. Камень с нулём -
--    это камень, который занимает гнездо и ничего не делает; обещание без
--    исполнения. Поднимаем такие до единицы.
--
-- 2. ЖЕЗЛЫ - НЕ РЕАГЕНТ. Запрос v29 брал весь подкласс «зачарование», а там
--    вместе с пылью и эссенциями лежат жезлы зачаровывателя: медный, рунный и
--    прочие. Это инструмент, его не тратят - вставкой он оказался по ошибке.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.5.

UPDATE `ap_material` m
SET m.`stat_value` = 1
WHERE m.`role` = 'insert' AND m.`stat_type` > 0 AND m.`stat_value` = 0;

DELETE m FROM `ap_material` m
JOIN `item_template` it ON it.`entry` = m.`entry`
WHERE m.`role` = 'insert'
  AND (it.`name` LIKE '%Rod%' OR it.`name` LIKE '%Runed Copper%');

-- Каталог поменялся: список вставок стал короче (§7, «Кэш каталога»).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
