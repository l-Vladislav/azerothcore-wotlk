-- mod-advanced-professions: осколок - редкость, и он поднимает вещь.
--
-- Правило доводки - строгое совпадение качества (§2.5): зелёный камень идёт
-- только в зелёную вещь. Это единственный рычаг, который держит число эскизов в
-- рамках, и отменять его незачем. Но владелец попросил исключение: «иногда из
-- зелёной основы можно получить синий предмет» - и держаться оно должно не на
-- случайности, а на редком материале в наборе.
--
-- Эту роль получают ОСКОЛКИ (род вставки `shard`): их в игре два десятка на все
-- качества, они выбиваются разрушением вещей, и «редкость» к ним идёт по
-- смыслу. Осколку качеством выше зелёного окно расширяется на ступень вниз:
-- синий идёт и в зелёную вещь, эпический - и в синюю.
--
-- Что из этого следует для игрока: положил в набор осколок лучше самой вещи -
-- и на выходе именной предмет ступенью выше. Не положил - выйдет то, что
-- обещала основа. Генератор эскизов (`tools/gen-synergies.py`) читает это же
-- правило и раздаёт такие наборы по одному на ступень, где они возможны.
--
-- Прочие материалы не трогаются: их строгое совпадение остаётся законом.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.5, §5.6.

UPDATE `ap_material` m
JOIN `item_template` it ON it.`entry` = m.`entry`
JOIN `ap_insert_type` t ON t.`id` = m.`insert_type_id`
SET m.`quality_min` = it.`Quality` - 1,
    m.`quality_max` = it.`Quality`
WHERE m.`role` = 'insert'
  AND t.`code` = 'shard'
  AND it.`Quality` >= 2;

-- Каталог меняется: у осколков теперь другое окно качества, и аддон гасит их в
-- списке гнезда по нему (§7, «Кэш каталога»).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
