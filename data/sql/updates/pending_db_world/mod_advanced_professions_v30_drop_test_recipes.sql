-- mod-advanced-professions: убрать тестовые рецепты и недостижимые эскизы.
--
-- Разбор содержимого 2026-09-13 показал, что из трёх заведённых рецептов целый
-- только один, а из трёх эскизов работает тоже один. Остальное - заглушки эпохи
-- «проверить механику», и они мешают: панель показывает их наравне с
-- настоящими, а игрок читает как обещание.
--
-- ЧТО УБИРАЕТСЯ И ПОЧЕМУ:
--
-- Рецепт 2 «Стальной клинок». Пять ступеней качества заявлено, а изделия -
-- ванильный хлам: `Worn Shortsword` (25) стоит сразу на трёх ступенях, на
-- пятой - `Worn Mace`, то есть БУЛАВА в рецепте типа «Меч». Все белые, значит у
-- любой ступени ровно одно гнездо: «легендарная» ступень ничем не отличается от
-- обычной.
--
-- Рецепт 3 «Мифриловый клинок». Ячейки заданы, изделий нет ни на одну ступень -
-- сервер так и пишет, «готовых=2» из трёх.
--
-- Эскиз 2 «Клинок исполина». Просит пять камней, а у всех ступеней рецепта 2 по
-- одному гнезду: собрать его нельзя в принципе.
--
-- Эскиз 1 «Клинок ловчего». Из зелёной или синей основы даёт БЕЛЫЙ предмет -
-- приз хуже того, из чего собран. Обесценивает работу.
--
-- ЧТО ОСТАЁТСЯ: рецепт 1 «Бронзовый клинок» с тремя ступенями (белая, зелёная,
-- синяя - гнёзд 1, 2, 3) и эскиз 13 «Клык Тьмы»: две вставки в зелёную основу
-- дают синий Shadowfang. Это образец того, как должно быть - приз лучше основы.
--
-- ЗАГОТОВКИ ПУЛА удалённых ступеней тоже уходят. Это безопасно ровно сейчас:
-- `ap_generated_item` пуст, ни одна заготовка никому не выдана, и ни у кого в
-- сумке такой вещи нет. Удаление всё равно идёт с проверкой - строка сносится
-- только если её id не значится выданным (§4, «Занятый ID не освобождается»).
--
-- Предметы 180004 и 180005 (призы снятых эскизов) остаются: это строки блока
-- панели, их владелец заводил руками и может переиспользовать.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.7, §5.6.

-- Заготовки снимаемых ступеней: сперва они, пока границы слайсов ещё известны.
DELETE it FROM `item_template` it
JOIN `ap_recipe_result` rr
  ON it.`entry` BETWEEN rr.`pool_lo` AND rr.`pool_hi`
WHERE rr.`recipe_id` IN (2, 3)
  AND rr.`pool_lo` > 0
  AND NOT EXISTS (SELECT 1 FROM `ap_generated_item` g WHERE g.`entry` = it.`entry`);

-- Эскизы: недостижимый и обесценивающий.
DELETE FROM `ap_synergy` WHERE `id` IN (1, 2);

-- Сами рецепты со всем, что к ним относится: ступени, ячейки, фильтры вставок
-- и поимённые списки материалов.
DELETE FROM `ap_recipe_result`      WHERE `recipe_id` IN (2, 3);
DELETE FROM `ap_recipe_item`        WHERE `recipe_id` IN (2, 3);
DELETE FROM `ap_recipe_insert_type` WHERE `recipe_id` IN (2, 3);
DELETE FROM `ap_recipe_material`    WHERE `recipe_id` IN (2, 3);
DELETE FROM `ap_recipe`             WHERE `id` IN (2, 3);

-- Каталог поменялся: у аддона он в кэше, и без этой строки окно будет рисовать
-- снятые рецепты до следующей правки справочника (§7, «Кэш каталога»).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
