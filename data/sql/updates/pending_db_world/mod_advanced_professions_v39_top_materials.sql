-- mod-advanced-professions: у верхних материалов нет потолка уровня.
--
-- Полоса уровня у вставки считалась от уровня самого камня с нахлёстом (v29):
-- камень восьмидесятого уровня получал окно 70-95. Пока речь шла о сетке основ,
-- этого хватало - её потолок 85. Но именные вещи Лича идут до двухсотого уровня
-- предмета и выше, и в них не вставал НИ ОДИН камень: замер геройских заготовок
-- показал 127 вещей, которым нечем доводиться.
--
-- Решение простое и уже записанное в дизайне: **собственный уровень камня не
-- важен** (§2.5), значение имеет только окно, которое мы ему назначили. У
-- верхних материалов потолок снимается вовсе - ноль значит «без верхней
-- границы». Нижняя остаётся: саронитовый самоцвет по-прежнему не полезет в
-- медный клинок.
--
-- Верхние - это те, чьё окно и так доходило до девяноста, то есть камни
-- семидесятого уровня и выше: эпические самоцветы Нордскола, большие эссенции,
-- осколки бездны. Ровно те, что и должны быть эндгеймом доводки.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.5.

UPDATE `ap_material`
SET `ilvl_max` = 0
WHERE `role` = 'insert' AND `ilvl_max` >= 90;

-- Каталог меняется: у верхних камней другое окно (§7, «Кэш каталога»).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
