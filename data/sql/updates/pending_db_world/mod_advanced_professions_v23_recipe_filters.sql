-- mod-advanced-professions: основа принимает не всё подряд.
--
-- Зачем. До сих пор в любое гнездо годился любой камень, прошедший качество и
-- границы уровня. Это и держало комбинаторику: эскизов у эпической основы
-- выходило 125 при пяти подходящих камнях. Но содержания в этом нет никакого -
-- костяная основа принимает самоцветы наравне с костью.
--
-- Фильтров ДВА, оба необязательные, и назначение у них разное (DESIGN §2.5,
-- «Какие материалы принимает основа»):
--
--   ap_recipe_insert_type | массовый | «костяные основы принимают кость»
--   ap_recipe_material    | точный   | «в этот клинок идут вот эти три камня»
--
-- Порядок отсева при вставке:
--
--   роль «в слот» -> качество -> уровень -> список ЛИБО набор типов
--
-- **Список, если задан, заменяет набор типов.** Иначе вышла бы ловушка: назвали
-- материал поимённо, а он не проходит, потому что тип не тот. Пустой список и
-- пустой набор типов значат «ограничения нет» - ровно как было.
--
-- Качество и границы уровня действуют ВСЕГДА: на качестве держится вся
-- арифметика гнёзд, а границы уровня - балансная защита.
--
-- Оба фильтра только сужают, поэтому эскизов становится меньше, а слайс пула
-- получает запас. Нишевая основа выходит самой дешёвой в системе: костяная
-- редкая при четырёх костях даёт 34 эскиза против 83 у обычной.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.5, §5.7.

CREATE TABLE IF NOT EXISTS `ap_recipe_insert_type` (
  `recipe_id`      INT UNSIGNED NOT NULL COMMENT 'ap_recipe.id',
  `insert_type_id` INT UNSIGNED NOT NULL COMMENT 'ap_insert_type.id',
  PRIMARY KEY (`recipe_id`, `insert_type_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='Какие типы вставки принимает основа. Строк нет - принимает любые';

CREATE TABLE IF NOT EXISTS `ap_recipe_material` (
  `recipe_id`  INT UNSIGNED NOT NULL COMMENT 'ap_recipe.id',
  `item_entry` INT UNSIGNED NOT NULL COMMENT 'ap_material.entry роли insert',
  PRIMARY KEY (`recipe_id`, `item_entry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  COMMENT='Поимённый список вставок основы. Строк нет - действует набор типов';

-- Данных не засеваем: пустые таблицы означают «принимает любые», то есть ровно
-- нынешнее поведение. Фильтры владелец расставит в панели там, где они нужны по
-- содержанию.
