-- mod-advanced-professions: чертежи ко всем рецептам.
--
-- Сетка основ есть (v32), а взять её негде: у всех рецептов `teach_item = 0`,
-- то есть узнать их можно только УГАДАВ точный набор. На медной полосе это
-- ещё мыслимо, дальше - нет: материалов под тысячу, а набор сверяется целиком,
-- включая количества и пустые ячейки. Новый игрок открывал верстак и видел
-- пустой список.
--
-- Здесь заводится книга на каждый рецепт: 79 чертежей в блоке 190000-199999,
-- по одному на «тип + полосу». Имя берётся у самого рецепта, а он уже
-- склонён по роду (v32): «Чертёж: Медный клинок», «Чертёж: Медная булава».
--
-- ВИД - ванильный чертёж кузнеца (displayid 1102): свёрнутый пергамент, тот
-- самый, каким игра рисует «Plans: ...». Игрок узнаёт его, не читая.
--
-- ПРИМЕНЕНИЕ - пять секунд (решение владельца 2026-09-13). Своего спелла у
-- книги нет: модуль перехватывает применение целиком, поэтому в `spellid_1`
-- стоит ванильное «Обучение» (483) - оно нужно ровно затем, чтобы клиент
-- показал у предмета кнопку «Использовать». Срок держит сервер тем же
-- порядком, что ковку и вставку; книга тратится и рецепт записывается только
-- когда чтение дошло до конца.
--
-- Раздачи в мире эта миграция не делает: где книги продаются и с кого падают -
-- отдельное решение. Пока их выдаёт администратор (.additem), а в панели они
-- видны у своего рецепта.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §5.4.4.

-- --------------------------------------------------------------------------
-- 1. Сроки и звук чтения
-- --------------------------------------------------------------------------
-- SoundEntries 605 - SPELLBOOKCHANGEPAGE, шорох переворачиваемой страницы.
INSERT IGNORE INTO `ap_config` (`name`, `value`, `comment`) VALUES
  ('book_time_ms', '5000',
   'Сколько миллисекунд читается книга рецепта; 0 - мгновенно'),
  ('book_sound', '605',
   'SoundEntries шелеста страницы при чтении (605 - SPELLBOOKCHANGEPAGE); '
   '0 - без звука'),
  ('book_sound_ms', '2500',
   'Шаг между шелестами страниц в миллисекундах; 0 - без звука');

-- --------------------------------------------------------------------------
-- 2. Повторный прогон
-- --------------------------------------------------------------------------
-- Номера рецептов меняются на каждом прогоне генератора сетки, поэтому книги
-- пересобираются вместе с ним. Сносим только свои - и только те, которых нет
-- ни у кого в сумке.
--
-- БЛОК ПОДЕЛЁН НАДВОЕ (2026-09-14): чертежи основ живут в 190000-190999, книги
-- эскизов - с 191000. Прежде обе половины брали «следующий за наибольшим» на
-- весь блок 190000-199999, и кто прогонялся вторым, тот и съезжал: после книг
-- эскизов чертежи уезжали за 191000, а повторный прогон книг вставал на их
-- место. Теперь у каждой половины свой угол.
UPDATE `ap_recipe` SET `teach_item` = 0
WHERE `acquire` = 'forge' AND `teach_item` BETWEEN 190000 AND 199999;

DELETE t FROM `item_template` t
WHERE t.`entry` BETWEEN 190000 AND 190999
  AND t.`name` LIKE 'Чертёж:%'
  AND NOT EXISTS (SELECT 1 FROM `ap_recipe` r WHERE r.`teach_item` = t.`entry`)
  AND NOT EXISTS (SELECT 1 FROM `ap_synergy` s WHERE s.`teach_item` = t.`entry`);

-- --------------------------------------------------------------------------
-- 3. Сами чертежи
-- --------------------------------------------------------------------------
SELECT COALESCE(MAX(`entry`), 189999) + 1 INTO @book_next
FROM `item_template` WHERE `entry` BETWEEN 190000 AND 190999;

DROP TEMPORARY TABLE IF EXISTS `ap_book`;
CREATE TEMPORARY TABLE `ap_book` (
  `recipe_id` INT UNSIGNED PRIMARY KEY,
  `entry`     INT UNSIGNED NOT NULL,
  `name`      VARCHAR(255) NOT NULL,
  `skill`     SMALLINT UNSIGNED NOT NULL
);

INSERT INTO `ap_book` (`recipe_id`, `entry`, `name`, `skill`)
SELECT r.`id`,
       @book_next + ROW_NUMBER() OVER (ORDER BY r.`type_id`, r.`req_skill`, r.`id`) - 1,
       CONCAT('Чертёж: ', r.`name_ru`),
       r.`req_skill`
FROM `ap_recipe` r
WHERE r.`teach_item` = 0
  AND r.`acquire` = 'forge';

-- Угол чертежей - тысяча номеров; если основ станет больше, прогон обязан
-- УПАСТЬ, и упасть ЗДЕСЬ - до вставки и до привязки. Первая версия проверки
-- стояла в конце, и упавший прогон успевал привязать сто шестнадцать рецептов
-- к чужим номерам (там лежали книги эскизов), а вставка молча проглатывала
-- дубли через INSERT IGNORE. Имена таблиц mysql разбирает до выполнения,
-- поэтому проверка идёт подготовленным запросом.
SET @overflow := (SELECT COUNT(*) FROM `ap_book` WHERE `entry` > 190999);
SET @check := IF(@overflow = 0,
                 'SELECT ''чертежи влезли в свой угол'' AS `проверка блока`',
                 'SELECT 1 FROM `ОШИБКА_чертежи_не_влезли_в_190000_190999`');
PREPARE `ap_check` FROM @check;
EXECUTE `ap_check`;
DEALLOCATE PREPARE `ap_check`;

-- `class` 9 / `subclass` 4 - «рецепт кузнеца»: клиент и сам покажет его как
-- чертёж, а сортировка сумки положит рядом с прочими рецептами.
--
-- Флагов не ставим вовсе: чертёж свободно торгуется, продаётся торговцу и
-- ничем не связан. `spellcharges_1 = -1` - «тратится при применении», как у
-- ванильных рецептов; сам расход делает модуль, когда чтение дошло до конца.
INSERT IGNORE INTO `item_template`
  (`entry`, `class`, `subclass`, `SoundOverrideSubclass`, `name`, `displayid`,
   `Quality`, `Flags`, `BuyCount`, `BuyPrice`, `SellPrice`, `InventoryType`,
   `Stackable`, `MaxCount`, `Material`, `Sheath`, `RequiredLevel`,
   `ItemLevel`, `bonding`, `spellid_1`, `spelltrigger_1`, `spellcharges_1`,
   `spellcooldown_1`, `spellcategory_1`, `spellcategorycooldown_1`)
SELECT b.`entry`, 9, 4, -1, b.`name`, 1102,
       1, 0, 1,
       -- Цена растёт с навыком: медный чертёж стоит медяки, саронитовый -
       -- десятки золотых. Продажная - четверть покупной, как у игры.
       GREATEST(200, b.`skill` * 400),
       GREATEST(50,  b.`skill` * 100),
       0, 1, 0, 8, 0, 0, 0, 0,
       483, 0, -1, 0, 0, 0
FROM `ap_book` b;

UPDATE `ap_recipe` r
JOIN `ap_book` b ON b.`recipe_id` = r.`id`
SET r.`teach_item` = b.`entry`;

DROP TEMPORARY TABLE IF EXISTS `ap_book`;

-- Каталог меняется: у рецептов появилась книга, и аддон показывает её в
-- подсказке строки (§7, «Кэш каталога»).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
