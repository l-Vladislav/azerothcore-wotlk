-- mod-advanced-professions: величину вставки считает полоса цели.
--
-- До сих пор величина камня росла от ЕГО СОБСТВЕННОГО уровня (v29):
-- `GREATEST(2, ilvl/8) + (качество - 2) * 2`. Про вещь, в которую камень
-- ляжет, формула не знала ничего, и разошлась с игрой в обе стороны сразу.
--
-- Замер вклада всех гнёзд против собственных статов основы:
--
--     полоса 1-19,   зелёная   - 1.4 у вещи против 7.1 от камней   (507 %)
--     полоса 50-89,  эпическая - 11.8 против 51.1                  (433 %)
--     полоса 90-139, эпическая - 65.6 против 56.0                   (85 %)
--     полоса 200+,   эпическая - 424.8 против 56.0                  (13 %)
--
-- Внизу камень вчетверо тяжелее вещи, в которую кладётся (малахит давал +4
-- ловкости там, где вся зелёная вещь несёт 1.6 стата), наверху - незаметен:
-- самоцветов выше 80-го уровня в игре нет, формула упиралась в потолок 14, а
-- v39 сняла этим камням верхнюю границу, и одни и те же 106 эпических
-- самоцветов ложились и в вещь 90-го уровня, и в вещь 264-го.
--
-- РЕШЕНИЕ ВЛАДЕЛЬЦА (2026-09-14, §2.12): полный набор камней добавляет вещи
-- ТРЕТЬ её собственного бюджета статов. Отсюда величина:
--
--     величина = бюджет полосы и качества / 3 / число гнёзд, но не меньше 1
--
-- Бюджет не выдуман, а ЗАМЕРЕН: это средняя сумма очков у ванильных вещей
-- нашего рода, той же полосы и того же качества. Правило само подстроится,
-- если полосы перекроят, и своей таблицы чисел не заводит.
--
-- ПОЛОСА МАТЕРИАЛА. Раз числа сырые (§5.7), одному камню полагается одна
-- полоса: величина у него одна, и растягивать её на четверть лестницы значит
-- снова промахиваться. Окно уровня сужается со «своего уровня ±10/+15» до
-- границ полосы. Раздаются камни так:
--
--   уровень до 64 - полоса по собственному уровню, как и было. Низ обязан
--     оставаться доступным: самоцвет Нордскола в медный клинок не попросишь;
--   уровень 65 и выше - весь этот сгусток (а в нём три четверти справочника:
--     огранка BC и Лича стоит 65-80 уровнями, а вещи под неё - от 90-го до
--     284-го) раскладывается по семи верхним полосам поровну ВНУТРИ каждой
--     пары «качество + стат». Порядок - по уровню камня, поэтому огранка BC
--     садится в адамантит и кориум, а Лича - в саронит, титансталь и титан.
--
-- Делить внутри пары «качество + стат», а не просто по рангу, обязательно:
-- камни одного цвета лежат в справочнике подряд, и сплошной ранг оставлял бы
-- полосы с одним-двумя статами на выбор (сегодня у синей полосы 20-49 ровно
-- четыре камня, и оба стата - дух да крит). После раздачи в каждой полосе
-- зелёного, синего и эпического качества 6-8 разных статов.
--
-- ЦВЕТ ЗНАЧИТ ОДНО И ТО ЖЕ. В v29 соответствий было два: у огранённого
-- самоцвета стат брался от подкласса (зелёный - дух), у простого от имени
-- (зелёный - ловкость). Владелец назвал своё: зелёный - ловкость, жёлтый -
-- сила, фиолетовый - интеллект, голубой - выносливость. Правило теперь одно
-- на всех, и огранённый зелёный перестаёт давать дух.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.12, §5.7.

-- --------------------------------------------------------------------------
-- 1. Цвет значит одно и то же
-- --------------------------------------------------------------------------
-- Только ванильные строки: у своих камней (185000-189999) имя русское,
-- и правило «цвет знает имя» сбросило бы им стат в дух. Свой камень
-- заводится сразу с нужным статом (v43).
-- Огранённые самоцветы: цвет знает подкласс.
UPDATE `ap_material` m
JOIN `item_template` g ON g.`entry` = m.`entry`
SET m.`stat_type` = CASE g.`subclass`
       WHEN 0 THEN 38   -- красный    - сила атаки
       WHEN 1 THEN 7    -- синий      - выносливость
       WHEN 2 THEN 4    -- жёлтый     - сила
       WHEN 3 THEN 5    -- фиолетовый - интеллект
       WHEN 4 THEN 3    -- зелёный    - ловкость
       WHEN 5 THEN 32   -- оранжевый  - критический удар
       WHEN 6 THEN 45   -- мета       - сила заклинаний
       ELSE 6           -- радужный   - дух
     END
WHERE m.`role` = 'insert' AND m.`entry` < 100000
  AND g.`class` = 3 AND g.`subclass` <> 7;

-- Простые самоцветы: цвет знает имя. Соответствие то же самое.
UPDATE `ap_material` m
JOIN `item_template` g ON g.`entry` = m.`entry`
SET m.`stat_type` = CASE
       WHEN g.`name` LIKE '%Malachite%' OR g.`name` LIKE '%Jade%'
         OR g.`name` LIKE '%Emerald%'   OR g.`name` LIKE '%Agate%'
         THEN 3
       WHEN g.`name` LIKE '%Tigerseye%' OR g.`name` LIKE '%Citrine%'
         OR g.`name` LIKE '%Topaz%'     OR g.`name` LIKE '%Amber%'
         THEN 4
       WHEN g.`name` LIKE '%Shadowgem%' OR g.`name` LIKE '%Amethyst%'
         OR g.`name` LIKE '%Opal%'
         THEN 5
       WHEN g.`name` LIKE '%Moonstone%' OR g.`name` LIKE '%Sapphire%'
         OR g.`name` LIKE '%Aquamarine%' OR g.`name` LIKE '%Pearl%'
         THEN 7
       WHEN g.`name` LIKE '%Ruby%' OR g.`name` LIKE '%Garnet%'
         THEN 38
       ELSE 6
     END
WHERE m.`role` = 'insert' AND m.`entry` < 100000
  AND g.`class` = 3 AND g.`subclass` = 7;

-- Окно качества 1-2 осталось у пяти строк от MVP, и это не правило, а хвост:
-- зелёный малахит лез в БЕЛУЮ основу и делал из неё зелёную вещь. Строгое
-- совпадение возвращается; расширенные окна осколков и кристаллов (2-3, 3-4)
-- не трогаются - на них держится исключение «через ступень» (v35).
UPDATE `ap_material`
SET `quality_min` = 0, `quality_max` = 0
WHERE `role` = 'insert' AND `quality_min` = 1 AND `quality_max` = 2;

-- --------------------------------------------------------------------------
-- 2. Полоса материала
-- --------------------------------------------------------------------------
DROP TEMPORARY TABLE IF EXISTS `ap_matband`;
CREATE TEMPORARY TABLE `ap_matband` (
  `entry`  INT UNSIGNED PRIMARY KEY,
  `q`      TINYINT UNSIGNED NOT NULL,
  `band`   TINYINT UNSIGNED NOT NULL,
  `spread` FLOAT NOT NULL DEFAULT 1,
  KEY (`band`, `q`)
);

INSERT INTO `ap_matband` (`entry`, `q`, `band`)
SELECT m.`entry`, g.`Quality`,
       CASE
         -- СВОЙ камень (блок 185000-189999) полосу называет сам: он заведён
         -- под конкретную клетку, и уровень предмета у него проставлен внутри
         -- её границ. Раздача по рангу тут только перепутала бы замысел.
         WHEN m.`entry` >= 185000 AND m.`entry` <= 189999 THEN
              (SELECT b2.`idx` FROM `ap_band` b2
               WHERE g.`ItemLevel` BETWEEN b2.`lo` AND b2.`hi` LIMIT 1)
         WHEN g.`ItemLevel` <= 14 THEN 0
         WHEN g.`ItemLevel` <= 24 THEN 1
         WHEN g.`ItemLevel` <= 34 THEN 2
         WHEN g.`ItemLevel` <= 44 THEN 3
         WHEN g.`ItemLevel` <= 54 THEN 4
         WHEN g.`ItemLevel` <= 64 THEN 5
         -- Сгусток 65+ раскладывается по семи верхним полосам поровну внутри
         -- пары «качество + стат». Признак `ItemLevel >= 65` стоит в разбиении
         -- нарочно: без него нумерация верхних сдвигалась бы от того, сколько
         -- в базе низких камней того же цвета.
         ELSE 5 + NTILE(7) OVER (
                    PARTITION BY IF(g.`ItemLevel` >= 65, 1, 0),
                                 g.`Quality`, m.`stat_type`
                    ORDER BY g.`ItemLevel`, m.`entry`)
       END
FROM `ap_material` m
JOIN `item_template` g ON g.`entry` = m.`entry`
-- ВСЕ вставки, включая снятые со стола, и это важно в обе стороны.
--
-- Полоса и величина - свойство самого камня, а не того, лежит ли он сейчас на
-- столе. Пока здесь стояло `enabled` = 1, выходило вот что: v45 идёт ПОСЛЕ
-- v42 и возвращает в строй камни из `ap_material_auto_off`, а числа им
-- посчитать уже некому - они остаются от того прогона, когда камень был
-- включён. Так «Defender's Dreadstone» доехал до сегодня с величиной 41 при
-- полосной 13, то есть втрое щедрее соседей по клетке.
--
-- Второе следствие важнее первого: раздача по полосам идёт `NTILE` по
-- ВЫБОРКЕ, и пока выборка зависела от включённости, каждый прогон v45
-- перетасовывал полосы у всех камней разом. Теперь выборка постоянная.
WHERE m.`role` = 'insert';

-- --------------------------------------------------------------------------
-- 2b. Разброс внутри клетки
-- --------------------------------------------------------------------------
-- Полоса задаёт величину, и до сих пор она задавала её ВСЕМ одинаково: два
-- десятка синих кобальтовых самоцветов давали ровно «+11» и отличались только
-- статом да именем. Справочник от этого плоский - искать лучший камень незачем,
-- достаточно первого попавшегося нужного цвета.
--
-- Поэтому внутри клетки числа расходятся на пятую часть в обе стороны: от 0.8
-- до 1.2 от полосной величины, по собственному уровню камня. Средняя по клетке
-- остаётся той же, то есть баланс полосы не двигается, а повод предпочесть
-- «Звёздный рубин» «Аквамарину» появляется.
DROP TEMPORARY TABLE IF EXISTS `ap_spread`;
CREATE TEMPORARY TABLE `ap_spread` AS
SELECT mb.`entry` AS `entry`,
       0.8 + 0.4 * (ROW_NUMBER() OVER (PARTITION BY mb.`band`, mb.`q`
                                       ORDER BY g.`ItemLevel`, mb.`entry`) - 1)
             / GREATEST(COUNT(*) OVER (PARTITION BY mb.`band`, mb.`q`) - 1, 1)
       AS `s`
FROM `ap_matband` mb
JOIN `item_template` g ON g.`entry` = mb.`entry`;

UPDATE `ap_matband` mb
JOIN `ap_spread` x ON x.`entry` = mb.`entry`
SET mb.`spread` = x.`s`;

DROP TEMPORARY TABLE IF EXISTS `ap_spread`;

-- --------------------------------------------------------------------------
-- 3. Бюджет полосы и величина камня
-- --------------------------------------------------------------------------
-- Бюджет - средняя сумма очков статов у ванильных вещей НАШИХ типов, попавших
-- в полосу своим уровнем предмета и своим качеством, УМНОЖЕННАЯ НА СТРИЖКУ.
--
-- Множитель стрижки (`ap_band_trim`, заводит v32) тут не украшение. Камень
-- ложится не в ванильную вещь, а в нашу ОСНОВУ, а основа - это донор, с
-- которого срезали четверть статов (три пятых на верхних полосах). Пока
-- бюджет мерился по непостриженному донору, «треть бюджета» выходила
-- две трети от того, что игрок держит в руках: замер по факту дал 73 % на
-- титане, 58 % на титанстали и 126 % на кобальтовой необычной ступени.
--
-- ЧИСТЫЕ СТАТЫ, а не все десять полей подряд. Сила атаки, сила заклинаний,
-- мана и здоровье лежат в тех же `stat_value`, но числами другого порядка: у
-- одного посоха 893 силы заклинаний против полутора сотен очков у целой
-- рейдовой вещи. Клетка, где ванильные вещи несут в основном их, получала
-- бюджет вдвое выше настоящего - а стат камня всегда обычный (ловкость, сила,
-- интеллект, дух, выносливость, рейтинг), и сравнивать его надо с таким же.
-- Своя проверка в audit.py находила восемь таких клеток.
--
-- МУСОР ИГРЫ отсекается по общему списку (`ap_junk_name`). Трёх `LIKE` не
-- хватало: `Naxxramas 40 Test God Sword` - эпическая вещь 80-го уровня с
-- 1407 очками статов - сидела в клетке двуручных мечей полосы 6 и тянула её
-- бюджет вверх на четверть.
DROP TEMPORARY TABLE IF EXISTS `ap_budget`;
CREATE TEMPORARY TABLE `ap_budget` (
  `band`   TINYINT UNSIGNED NOT NULL,
  `q`      TINYINT UNSIGNED NOT NULL,
  `budget` FLOAT NOT NULL,
  PRIMARY KEY (`band`, `q`)
);

-- СПИСОК ИСКЛЮЧЁННЫХ СТАТОВ - ИЗ `ap_stat_budget` (v47), а не строкой на месте.
-- Он стоял здесь двадцать раз и ещё четырьмя сырыми суммами в v32, где сила
-- атаки в бюджет ВХОДИЛА, - и лестница качества раздувала ступени по этой
-- сумме. Список у правила должен быть один.
--
-- ЗАМЕР ИДЁТ ПО НАШИМ СТУПЕНЯМ, а ванильные вещи - только запасной путь.
--
-- «Треть бюджета» - это треть бюджета ТОЙ ВЕЩИ, В КОТОРУЮ КАМЕНЬ ЛЯЖЕТ, и
-- вещь эта - наша ступень, а не ванильная вещь полосы. Замер по ванили со
-- стрижкой - хорошее приближение, но приближение: на полосе 140-174 у
-- необычных ступеней 15 очков против 20 по расчёту, и камень выходил
-- половиной бюджета вместо трети.
--
-- Ступени берутся, только если их в клетке хотя бы три: по одной-двум
-- среднее скачет сильнее, чем ошибка приближения. Клетку без ступеней (а на
-- первом прогоне таких клеток все) закрывает прежний путь - ванильные вещи,
-- умноженные на стрижку.
INSERT INTO `ap_budget` (`band`, `q`, `budget`)
SELECT c.`band`, c.`q`, COALESCE(c.`own`, c.`vanilla`, 0)
FROM (
  SELECT b.`idx` AS `band`, qq.`quality` AS `q`,
         (SELECT AVG(
           (SELECT `total` FROM `ap_item_budget`
            WHERE `entry` = bs.`entry`)
                    )
          FROM `ap_recipe_result` rr
          JOIN `ap_recipe` r ON r.`id` = rr.`recipe_id`
                            AND r.`enabled` = 1 AND r.`acquire` = 'forge'
          JOIN `item_template` bs ON bs.`entry` = rr.`result_entry`
          WHERE bs.`Quality` = qq.`quality`
            AND bs.`ItemLevel` BETWEEN b.`lo` AND b.`hi`
          HAVING COUNT(*) >= 3) AS `own`,
         (SELECT AVG(
           (SELECT `total` FROM `ap_item_budget`
            WHERE `entry` = p.`entry`)
                    ) * COALESCE(tr.`k_stat`, 1.0)
          FROM `item_template` p
          JOIN `ap_item_type` t ON t.`enabled` = 1
                               AND t.`item_class` = p.`class`
                               AND t.`item_subclass` = p.`subclass`
          WHERE p.`entry` < 100000
            AND p.`Quality` = qq.`quality`
            AND p.`ItemLevel` BETWEEN b.`lo` AND b.`hi`
            AND p.`name` <> ''
            AND NOT EXISTS (SELECT 1 FROM `ap_junk_name` j
                            WHERE p.`name` REGEXP j.`pattern`)) AS `vanilla`
  FROM `ap_band` b
  JOIN `ap_quality` qq ON qq.`quality` BETWEEN 1 AND 4
  LEFT JOIN `ap_band_trim` tr ON tr.`band` = b.`idx`
) c;

-- Величина: треть бюджета на все гнёзда, но не меньше единицы. Камень, не
-- дающий чисел, запрещён (§2.5) - он занимал бы гнездо впустую.
--
-- Считается всё в СУММЕ на вещь, и только в самом конце делится на гнёзда:
-- иначе два накопительных максимума спорили бы с округлением.
--
-- Максимумов как раз два, и оба лечат перекосы замера.
--
--   ПО ПОЛОСАМ - клетки, где ванильных вещей нет вовсе (саронитовой эпической,
--     например) или где их две-три и среднее проваливается: зелёных вещей
--     175-199 в игре два десятка, и они беднее зелёных 140-174;
--   ПО КАЧЕСТВУ - клетки, где эпических вещей полосы меньше, чем синих, и
--     замер выдаёт эпику МЕНЬШЕ синего. На полосе 140-174 синие несут 98
--     очков, а эпические 86: без этого прохода синий камень давал бы 17, а
--     эпический 7, и лишнее гнездо оборачивалось бы потерей.
--
-- Лестница обязана идти вверх в обе стороны - как и у самих основ.
-- Таблица ПОСТОЯННАЯ, как и сами полосы: по ней считает величину не только эта
-- миграция, но и всё, что заводит свои камни (v43). Два списка одного и того
-- же правила - способ, которым здесь уже дважды разъезжались лестницы.
CREATE TABLE IF NOT EXISTS `ap_band_value` (
  `band` TINYINT UNSIGNED NOT NULL,
  `q`    TINYINT UNSIGNED NOT NULL,
  `val`  SMALLINT UNSIGNED NOT NULL,
  PRIMARY KEY (`band`, `q`)
);
DELETE FROM `ap_band_value`;

-- Последний максимум - по числу НА КАМНЕ, а не на вещи. Игрок читает в
-- справочнике величину одного камня, и эпический, дающий меньше синего, для
-- него просто ошибка, сколько бы ни выходило в сумме по четырём гнёздам.
INSERT INTO `ap_band_value` (`band`, `q`, `val`)
SELECT `band`, `q`,
       GREATEST(1, MAX(ROUND(`by_quality` / `slots`))
                   OVER (PARTITION BY `band` ORDER BY `q`
                         ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW))
FROM (
  SELECT `band`, `q`, `slots`,
         MAX(`by_band`) OVER (PARTITION BY `band` ORDER BY `q`
                              ROWS BETWEEN UNBOUNDED PRECEDING
                                       AND CURRENT ROW) AS `by_quality`
  FROM (
    SELECT `band`, `q`, `slots`,
           MAX(`total`) OVER (PARTITION BY `q` ORDER BY `band`
                              ROWS BETWEEN UNBOUNDED PRECEDING
                                       AND CURRENT ROW) AS `by_band`
    FROM (
      SELECT b.`idx` AS `band`, qq.`quality` AS `q`, qq.`slots` AS `slots`,
             COALESCE(bg.`budget`, 0) / 3 AS `total`
      FROM `ap_band` b
      JOIN `ap_quality` qq ON qq.`quality` BETWEEN 1 AND 4
      LEFT JOIN `ap_budget` bg ON bg.`band` = b.`idx`
                              AND bg.`q` = qq.`quality`
    ) t1
  ) t2
) t3;

-- --------------------------------------------------------------------------
-- 4. Правка справочника
-- --------------------------------------------------------------------------
-- У верхней полосы потолка нет: вещей выше 284-го уровня в игре не бывает, но
-- геройская заготовка берёт уровень у своего приза, и запирать её незачем.
UPDATE `ap_material` m
JOIN `ap_matband` mb ON mb.`entry` = m.`entry`
JOIN `ap_band` b ON b.`idx` = mb.`band`
JOIN `ap_band_value` v ON v.`band` = mb.`band` AND v.`q` = mb.`q`
LEFT JOIN `ap_stat_weight` w ON w.`stat_type` = m.`stat_type`
-- Вес стата (`ap_stat_weight`, заводит v47) переводит полосную величину из
-- обычных очков в очки ЭТОГО стата. Единственный, у кого вес не единица, -
-- сила атаки: в 3.3.5 одна сила даёт две силы атаки, и камень на 33 силы
-- атаки рядом с камнем на 41 силы был не выбором, а ловушкой - ровно вдвое
-- дешевле соседа при одинаковом виде в справочнике. Бюджет полосы эти поля
-- вообще не считает (они «другого порядка»), так что раздавать их по общей
-- шкале значило объявить их несравнимыми и тут же сравнить.
SET m.`ilvl_min`   = b.`lo`,
    m.`ilvl_max`   = IF(b.`idx` = 12, 0, b.`hi`),
    m.`stat_value` = GREATEST(1, ROUND(v.`val` * mb.`spread`
                                       * COALESCE(w.`weight`, 1.0)));

-- --------------------------------------------------------------------------
-- 5. Проверка: пустой ответ - сходится
-- --------------------------------------------------------------------------
-- Камень без чисел или без полосы - это гнездо, которое нечем занять, и
-- молчать об этом нельзя. Имена таблиц mysql разбирает до выполнения, поэтому
-- ветка `IF` с несуществующей таблицей роняла бы запрос всегда: отсюда
-- подготовленный запрос.
SELECT COUNT(*) INTO @broken
FROM `ap_material` m
LEFT JOIN `ap_matband` mb ON mb.`entry` = m.`entry`
WHERE m.`role` = 'insert' AND m.`enabled` = 1
  AND (mb.`entry` IS NULL OR m.`stat_value` < 1 OR m.`stat_type` = 0);

SET @chk := IF(@broken = 0,
               'SELECT ''вставки в порядке'' AS `проверка`',
               'SELECT 1 FROM `ОШИБКА_вставка_без_полосы_или_без_чисел`');
PREPARE `chk` FROM @chk;
EXECUTE `chk`;
DEALLOCATE PREPARE `chk`;

DROP TEMPORARY TABLE IF EXISTS `ap_matband`;
DROP TEMPORARY TABLE IF EXISTS `ap_budget`;

-- Справочник сменился целиком: аддон держит его в кэше по версии (§7).
UPDATE `ap_config` SET `value` = `value` + 1 WHERE `name` = 'catalog_version';
