-- mod-advanced-professions: обязательные ячейки схемы типа.
--
-- v15 убрала у ячейки все настройки разом, и вместе с процентами вклада ушёл
-- флаг `required`. Тогда это было верно: он значил «в этой части обязан лежать
-- материал», а материал брался откуда угодно, потому что предмет считался из
-- свойств того, что положили. Пустая ячейка после разворота стала законной
-- частью набора, и требовать заполнения было незачем.
--
-- Но у схемы осталась вторая, чисто игровая сторона: **бывают части, без
-- которых вещи не существует**. Одноручный меч - это клинок, гарда и рукоять;
-- древковое - древко, втулка и наконечник. Навершие у меча украшение, его
-- можно не ставить, а вот меч без клинка не меч, из чего его ни собирай.
--
-- Отсюда флаг возвращается, но значит теперь другое (DESIGN §5.4.1):
--
--   было (v7):  «ячейку нельзя оставить пустой, иначе материалов не хватит
--                на расчёт характеристик»;
--   стало (v16): «ячейка входит в самое понятие этого предмета» - схема типа
--                говорит, из чего он сделан, а не что почём.
--
-- Что из этого следует для рецептов: рецепт, который обязательную ячейку не
-- называет (то есть требует её пустой), сковать нельзя вовсе - ковка откажет
-- до расхода материалов. Панель такой рецепт не даёт включить и пишет это в
-- списке причин, а сервер проверяет то же самое перед расходом.
--
-- Умолчание колонки - НОЛЬ, «не обязательна»: обязательность это утверждение о
-- предмете, и делать его владельцу в панели. Но выкатывать механику, которой
-- нигде не видно, бессмысленно, поэтому ниже идёт засев по десяти типам из v6 -
-- осторожный, с проверкой, что он не сделает некуемым уже включённый рецепт.

DROP PROCEDURE IF EXISTS `ap_add_column`;
DELIMITER $$
CREATE PROCEDURE `ap_add_column`(IN tbl VARCHAR(64), IN col VARCHAR(64),
                                 IN spec VARCHAR(255))
BEGIN
  IF (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = tbl
        AND COLUMN_NAME = col) = 0 THEN
    SET @s := CONCAT('ALTER TABLE `', tbl, '` ADD COLUMN `', col, '` ', spec);
    PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;
  END IF;
END$$
DELIMITER ;

CALL `ap_add_column`('ap_type_part', 'required',
  'TINYINT UNSIGNED NOT NULL DEFAULT 0 COMMENT ''1 = без этой части предмета не существует: пустой её оставить нельзя''');

DROP PROCEDURE IF EXISTS `ap_add_column`;

-- Аддон узнаёт обязательность из протокола (поле в строке PART), а не из своей
-- статики, поэтому версию справочника трогать не надо. Протокол при этом
-- меняется: 11 -> 12, и старый аддон окно рисовать откажется - так и задумано,
-- иначе игрок жал бы «Ковать» и получал отказ без объяснения.

-- --------------------------------------------------------------------------
-- Засев по типам из v6: какая часть держит само понятие предмета
-- --------------------------------------------------------------------------
-- Умолчание колонки - ноль, и колонка сама по себе ничего не меняет. Но
-- оставить все десять типов пустыми значит выкатить механику, которой нигде не
-- видно, поэтому засеваем схемы, заведённые v6:
--
--   меч        - рукоять, гарда, клинок (навершие - украшение);
--   древковое  - древко, втулка, наконечник (обмотка - украшение);
--   и так далее по той же мысли: несущая часть плюс ударная.
--
-- Ищем по ПОДПИСИ, а не по номеру: подписи из v6 владелец мог поменять, и тогда
-- строка просто не найдётся - лучше не отметить ничего, чем отметить не то.
--
-- И только там, где это никого не ломает: тип, у которого есть ВКЛЮЧЁННЫЙ
-- рецепт, оставляющий такую ячейку пустой, пропускаем целиком. Иначе миграция
-- сделала бы рабочий рецепт некуемым молча - ровно то, за чем панель следит
-- отдельно (§8). Такие типы владелец отметит сам, когда допишет наборы.
UPDATE `ap_type_part` `tp`
   SET `tp`.`required` = 1
 WHERE (`tp`.`type_id`, `tp`.`label_ru`) IN (
        (1, 'Рукоять'), (1, 'Гарда'), (1, 'Клинок'),
        (2, 'Рукоять'), (2, 'Гарда'), (2, 'Клинок'),
        (3, 'Рукоять'), (3, 'Гарда'), (3, 'Клинок'),
        (4, 'Топорище'), (4, 'Лезвие'),
        (5, 'Древко'), (5, 'Лезвие'),
        (6, 'Рукоять'), (6, 'Навершие'),
        (7, 'Древко'), (7, 'Боёк'),
        (8, 'Древко'), (8, 'Втулка'), (8, 'Наконечник'),
        (9, 'Ремень'), (9, 'Ударная пластина'),
        (10, 'Поле'), (10, 'Ремни'))
   AND NOT EXISTS (
        SELECT 1 FROM `ap_recipe` `r`
         WHERE `r`.`type_id` = `tp`.`type_id`
           AND `r`.`enabled` = 1
           AND NOT EXISTS (
                SELECT 1 FROM `ap_recipe_item` `ri`
                 WHERE `ri`.`recipe_id` = `r`.`id`
                   AND `ri`.`part_idx` = `tp`.`idx`
                   AND `ri`.`item_entry` > 0));
