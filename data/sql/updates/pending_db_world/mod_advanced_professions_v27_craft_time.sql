-- mod-advanced-professions: ковка занимает время, и у неё есть звук.
--
-- Зачем. Ковка была мгновенной: нажатие - и предмет в сумке. В игре ремесло
-- так себя не ведёт, и дело не в украшении: пауза отделяет решение от его
-- последствия. Именно в эти секунды видно, что работа идёт, а материалы уже
-- назад не возьмёшь.
--
-- Срок держит СЕРВЕР, а не аддон: заказ принимается командой craft, ложится в
-- очередь и ждёт своего события. Аддон по ответу OK:BEGIN:<мс> заливает
-- кнопку, но полоса эта - отражение чужого таймера, а не сам таймер.
--
-- Проверка идёт дважды - на входе и на исходе срока. За десять секунд игрок
-- успевает продать слитки или набить сумку доверху, поэтому набор
-- пересчитывается заново перед самым расходом. Замораживать материалы на это
-- время не стали: это ещё одно состояние предмета, которое переживает выход
-- из игры, а перепроверка не оставляет следов вовсе.
--
-- Звук - SoundEntries 4614 (BlackSmithCraftingA..E), тот самый набор, которым
-- звучит кузнечное дело самой игры. Удары расставлены по сроку с шагом
-- craft_sound_ms; ноль в любом из двух чисел выключает звук целиком.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §5.4.6.
INSERT IGNORE INTO `ap_config` (`name`, `value`, `comment`) VALUES
  ('craft_time_ms', '10000',
   'Сколько миллисекунд идёт ковка; 0 - мгновенно, как было до v27'),
  ('craft_sound', '4614',
   'SoundEntries удара молота во время ковки (4614 - BlackSmithCrafting); '
   '0 - без звука'),
  ('craft_sound_ms', '2500',
   'Шаг между ударами молота в миллисекундах; 0 - без звука');
