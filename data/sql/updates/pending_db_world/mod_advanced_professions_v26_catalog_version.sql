-- mod-advanced-professions: версия каталога для кэша в аддоне.
--
-- Зачем. Открытие верстака шлёт весь справочник целиком: рода и типы вставки,
-- типы предметов с ячейками, список материалов и фильтры вставок у каждого
-- рецепта. Пока материалов дюжина, это десяток строк; после разворота §2.5 их
-- 554, а рецептов-основ 582 - то есть под сотню чат-пакетов на КАЖДОЕ открытие
-- окна. На этом сервере болтливый протокол уже давал микрофризы (item-talents,
-- лечилось батчингом), и повторять это незачем: справочник у всех игроков один
-- и тот же и меняется только из панели.
--
-- Отсюда `catalog_version`. Аддон везёт свою версию в `.aprof open <версия>`,
-- сервер сверяет её со своей и справочник шлёт ТОЛЬКО при расхождении. Остатки
-- материалов в сумке при этом уезжают всегда - они у каждого свои и в кэш не
-- годятся, для них есть отдельная короткая запись `HAVE`.
--
-- Почему отдельное число, а не `static_version`: та версия про ТЕКСТЫ (подписи
-- типов и частей, названия качеств), и на её расхождение аддон ходит за ними
-- командой `.aprof static`. Смешать их значит гонять тексты при каждой правке
-- камня, а каталог - при каждой правке подписи.
--
-- Панель поднимает число, когда правит что-либо из каталога: справочники,
-- материалы, типы, ячейки, фильтры вставок у рецепта и настройку `fail_mode`.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §7, §11 пункт 11.
