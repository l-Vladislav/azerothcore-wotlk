CREATE TEMPORARY TABLE `worn_balance_item` (`entry` INT UNSIGNED NOT NULL PRIMARY KEY, `ItemLevel` SMALLINT UNSIGNED NOT NULL, `armor` SMALLINT UNSIGNED NOT NULL, `block` INT UNSIGNED NOT NULL, `dmg_min1` FLOAT NOT NULL, `dmg_max1` FLOAT NOT NULL, `dmg_min2` FLOAT NOT NULL, `dmg_max2` FLOAT NOT NULL);

INSERT INTO `worn_balance_item`
SELECT x.`entry`, x.`ItemLevel`, x.`armor`, x.`block`,
    IF(x.`dmg_total` IS NULL, x.`dmg_min1`, x.`dmg_min_new`),
    IF(x.`dmg_total` IS NULL, x.`dmg_max1`, GREATEST(x.`dmg_min_new` + 1, x.`dmg_total` - x.`dmg_min_new`)),
    IF(x.`dmg_total` IS NULL, x.`dmg_min2`, 0),
    IF(x.`dmg_total` IS NULL, x.`dmg_max2`, 0)
FROM (
    SELECT it.`entry`, wb.`ItemLevel`,
        IF(it.`armor` > 0 AND wb.`armor` IS NOT NULL, wb.`armor`, it.`armor`) AS `armor`,
        IF(it.`block` > 0 AND wb.`block` IS NOT NULL, wb.`block`, it.`block`) AS `block`,
        it.`dmg_min1`, it.`dmg_max1`, it.`dmg_min2`, it.`dmg_max2`,
        IF(it.`dmg_max1` > 0 AND it.`delay` > 0 AND wb.`dps` IS NOT NULL,
            ROUND(wb.`dps` * it.`delay` / 500), NULL) AS `dmg_total`,
        GREATEST(1, ROUND(ROUND(wb.`dps` * it.`delay` / 500) * it.`dmg_min1` / (it.`dmg_min1` + it.`dmg_max1`)))
            AS `dmg_min_new`
    FROM `item_template` it
    JOIN `worn_drop_item` wdi ON wdi.`item_entry` = it.`entry`
    JOIN `worn_balance` wb ON wb.`class` = it.`class` AND wb.`subclass` = it.`subclass`
        AND wb.`InventoryType` = it.`InventoryType` AND wb.`RequiredLevel` = it.`RequiredLevel`
        AND wb.`Quality` = it.`Quality`
    WHERE it.`entry` BETWEEN 400000 AND 1099999) x;

UPDATE `item_template` it
JOIN `worn_balance_item` b ON b.`entry` = it.`entry`
SET it.`ItemLevel` = b.`ItemLevel`, it.`armor` = b.`armor`, it.`block` = b.`block`,
    it.`dmg_min1` = b.`dmg_min1`, it.`dmg_max1` = b.`dmg_max1`,
    it.`dmg_min2` = b.`dmg_min2`, it.`dmg_max2` = b.`dmg_max2`;

