-- mod-advanced-weather: связи зон
--
-- Погода источника переносится соседу с ослаблением: 100% - та же самая,
-- слабее - на столько же ступеней ниже по лестнице своего семейства. Гроза
-- (4-я ступень дождя) при связи 49% приезжает соседу обычным дождём.
-- Подробности - modules/mod-advanced-weather/README.md.
--
-- ИСТОЧНИК ПРАВДЫ - админ-панель (tools/admin-panel, страница «Погода»):
-- здесь лежит стартовый набор географических связей, дальше их правят там,
-- а сервер перечитывает командой ".aw linkreload". Поэтому INSERT IGNORE:
-- повторный прогон файла не затирает правки из панели.
--
-- Связи направленные, но география симметрична, поэтому каждая пара записана
-- в обе стороны: удалить одну сторону из панели можно отдельно.

CREATE TABLE IF NOT EXISTS `mod_advanced_weather_zone_link` (
  `zone_id`     INT UNSIGNED     NOT NULL                COMMENT 'зона-источник погоды',
  `linked_zone` INT UNSIGNED     NOT NULL                COMMENT 'зона-получатель',
  `strength`    TINYINT UNSIGNED NOT NULL DEFAULT 100    COMMENT 'сила связи, 1-100%',
  `enabled`     TINYINT UNSIGNED NOT NULL DEFAULT 1,
  `comment`     VARCHAR(255)     NOT NULL DEFAULT ''     COMMENT 'зачем связь, для панели',
  PRIMARY KEY (`zone_id`, `linked_zone`),
  KEY `idx_linked` (`linked_zone`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='mod-advanced-weather: перенос погоды между зонами';

