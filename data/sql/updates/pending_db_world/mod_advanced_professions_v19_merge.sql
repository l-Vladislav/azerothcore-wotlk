-- mod-advanced-professions: объединение - третий род рецепта.
--
-- Замысел владельца 2026-09-05. У профессии появляется третий стол: на него
-- кладут ГОТОВУЮ ВЕЩЬ и до пяти любых предметов, а выходит другой предмет.
--
--   центральная вещь + набор из пяти ячеек  ->  ap_merge.result_entry
--
-- Чем это отличается от двух других столов:
--
--   ковка          собирает вещь ИЗ МАТЕРИАЛОВ по схеме типа;
--   инкрустация    добивает СВОЮ вещь камнями, и набор решает, выйдет ли
--                  именной предмет;
--   объединение    берёт ЛЮБУЮ вещь подходящего типа - выбитую в мире,
--                  купленную, скованную здесь - и переплавляет её вместе с
--                  чем угодно в новый предмет.
--
-- Решения владельца, из которых растёт эта схема:
--
-- * **в центр идёт любая вещь подходящего типа**, а не только изделие
--   верстака. Подходящий тип - это класс и подкласс из `ap_item_type`, то есть
--   от меча до щита; брони среди них нет, и потому нагрудник в центр не ляжет;
-- * **на выходе фиксированный предмет** - готовая строка `item_template`, как
--   у ковки. Центральная вещь при этом тратится: она сырьё, а не заготовка;
-- * **навыка объединение не требует и не поднимает**, как инкрустация. Броска
--   нет, провалиться нечем;
-- * **набор сравнивается как множество**: пять ячеек равноправны, порядок в
--   них не значит ничего. Нужно два одинаковых предмета - занимают две ячейки;
-- * **несовпавший набор ничего не тратит**: сервер отказывает до расхода.
--   Объединение - это применение НАЙДЕННОГО рецепта, а не угадывание, и
--   сжигать чужую вещь за неверную догадку не за что.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §5.8.

CREATE TABLE IF NOT EXISTS `ap_merge` (
  `id`           INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  `name_ru`      VARCHAR(64)      NOT NULL DEFAULT '' COMMENT 'Имя рецепта в панели; игрок видит имя предмета-результата',
  `type_id`      INT UNSIGNED     NOT NULL DEFAULT 0 COMMENT 'ap_item_type.id: какого рода вещь кладут в центр',
  `result_entry` INT UNSIGNED     NOT NULL DEFAULT 0 COMMENT 'item_template.entry на выходе. 0 - рецепт нерабочий',
  `teach_item`   INT UNSIGNED     NOT NULL DEFAULT 0 COMMENT 'entry обучающего предмета. 0 - рецепт только находят',
  `enabled`      TINYINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_ap_merge_type` (`type_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

-- Ячейка набора. Количества у ячейки нет намеренно: ячеек пять, они
-- равноправны, и «два слитка» - это две ячейки, а не число в одной. Так набор
-- остаётся тем, что игрок видит на столе, без скрытой арифметики.
CREATE TABLE IF NOT EXISTS `ap_merge_item` (
  `merge_id`   INT UNSIGNED     NOT NULL,
  `idx`        TINYINT UNSIGNED NOT NULL COMMENT 'Порядок в панели, 1..5. На сравнение не влияет',
  `item_entry` INT UNSIGNED     NOT NULL COMMENT 'item_template.entry: что кладут в ячейку',
  PRIMARY KEY (`merge_id`, `idx`),
  KEY `idx_ap_merge_item_entry` (`item_entry`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
