-- mod-advanced-professions: набор без рецепта - это неудача, а не отказ.
--
-- Раньше ковка набора, который не сошёлся ни с одним рецептом, просто
-- отказывала: материалы целы, но и понять, что игрок делает не так, нельзя.
-- Теперь поведение выбирается настройкой `fail_mode`:
--
--   0 - отказать, как раньше (материалы целы);
--   1 - съесть материалы, предмета нет (навык при этом растёт);
--   2 - выдать испорченную поделку серого качества (по умолчанию).
--
-- Испорченная поделка - это качество 0: слотов нет, вклад частей урезан до
-- `fail_pct` процентов, прок снят. Собирается по скелету самой простой основы
-- типа, поэтому класс, слот и внешний вид остаются осмысленными, а имя движок
-- склонений строит как «Испорченный бронзовый клинок».
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §5.4.2

-- --------------------------------------------------------------------------
-- Качество 0: строка нужна, чтобы у поделки было имя, ноль слотов и ноль
-- процентов к статам вставок. Без неё модуль возьмёт умолчание «1 слот».
-- --------------------------------------------------------------------------
INSERT INTO `ap_quality` (`quality`, `name_ru`, `slots`, `stat_pct`)
VALUES (0, 'Испорченная', 0, 0)
ON DUPLICATE KEY UPDATE `name_ru` = VALUES(`name_ru`),
                        `slots` = VALUES(`slots`),
                        `stat_pct` = VALUES(`stat_pct`);

-- --------------------------------------------------------------------------
-- Настройки. Значения не перетираем: владелец мог их уже покрутить.
-- --------------------------------------------------------------------------
INSERT IGNORE INTO `ap_config` (`name`, `value`, `comment`) VALUES
('fail_mode', '2',
 'Набор без рецепта: 0 - отказать, 1 - съесть материалы, 2 - серая поделка'),
('fail_pct', '50',
 'Сколько процентов от вклада частей остаётся у испорченной поделки');
