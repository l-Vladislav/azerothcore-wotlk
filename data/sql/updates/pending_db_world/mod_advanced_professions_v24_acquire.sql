-- mod-advanced-professions: у основы появился способ получения.
--
-- Зачем. Поле несущее, а не удобство: без него игрок сковал бы эпическую основу
-- на верстаке и обошёл рейд (DESIGN §2.5, «Основы»).
--
--   forge | обычный рецепт: ячейки, материалы, бросок на успех, поделка
--   drop  | сковать нельзя вовсе, основа приходит только добычей
--
-- Сам дроп задаётся не модулем, а таблицами добычи: со стороны профессии это
-- просто «на верстаке недоступно». Ожидаемая раскладка - низ куётся, верх
-- выбивается: профессия становится способом ДОВЕСТИ добытое, а не заменить его.
--
-- Что меняется для дроп-основы:
--
--   * правило «рецепт обязан назвать хотя бы одну ячейку» и требование назвать
--     все обязательные ячейки на неё не распространяются - в сравнении наборов
--     она не участвует, ячеек у неё может не быть ни одной;
--   * панель прячет ковочную половину (ячейки, навык, обучающий предмет) и
--     проверяет только доводочную: качество, изделия, фильтры вставок, эскизы;
--   * аддон её на вкладке ковки не показывает - и даром: изученной она не
--     станет, потому что изучение происходит на ковке, а её тут нет;
--   * поделка у неё не срабатывает никогда - проваливаться негде.
--
-- Ни слайсов, ни резерва, ни арифметики эскизов способ получения не меняет.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §2.5, «Основы».

DROP PROCEDURE IF EXISTS `ap_add_column`;
DELIMITER $$
CREATE PROCEDURE `ap_add_column`(IN tbl VARCHAR(64), IN col VARCHAR(64),
                                 IN spec VARCHAR(255))
BEGIN
  IF (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = tbl
        AND COLUMN_NAME = col) = 0 THEN
    SET @sql = CONCAT('ALTER TABLE `', tbl, '` ADD COLUMN `', col, '` ', spec);
    PREPARE stmt FROM @sql;
    EXECUTE stmt;
    DEALLOCATE PREPARE stmt;
  END IF;
END$$
DELIMITER ;

-- Умолчание `forge`: все нынешние рецепты именно кованые, и миграция не должна
-- менять поведение ни одного из них.
CALL `ap_add_column`('ap_recipe', 'acquire',
  "ENUM('forge','drop') NOT NULL DEFAULT 'forge' COMMENT 'forge - куётся на верстаке; drop - только добыча, ковать нельзя'");

DROP PROCEDURE IF EXISTS `ap_add_column`;
