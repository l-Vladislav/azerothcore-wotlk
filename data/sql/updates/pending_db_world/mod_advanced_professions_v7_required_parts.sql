-- mod-advanced-professions: часть может быть НЕОБЯЗАТЕЛЬНОЙ.
--
-- До этой миграции схема типа была жёсткой: сколько частей описано, столько
-- материалов и требуй, иначе ковка отказывала («Выберите материал для каждой
-- части»). Это мешает вещам, у которых часть - украшение: навершие посоха,
-- умбон щита, оплётка рукояти. Такой предмет собирается и без них, просто
-- выходит проще.
--
-- Теперь у части есть флаг `required`. Обязательная (значение по умолчанию -
-- прежнее поведение) должна получить материал; необязательную можно оставить
-- пустой, и тогда она просто ничего не приносит: ни урона, ни прочности, ни
-- уровня предмета, ни прока.
--
-- Рецепты основ это не ломает: условие рецепта «в части N лежит материал X»
-- по пустой части просто не совпадёт, и такая основа не выберется.
--
-- Дизайн: .claude/advanced-professions/DESIGN.md §5.4

SET @add := (SELECT COUNT(*) FROM information_schema.COLUMNS
             WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'ap_type_part'
               AND COLUMN_NAME = 'required');
SET @sql := IF(@add = 0,
    'ALTER TABLE `ap_type_part` '
    'ADD COLUMN `required` TINYINT UNSIGNED NOT NULL DEFAULT 1 '
    'COMMENT ''0 - часть можно оставить пустой'' AFTER `count`',
    'DO 0');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;
