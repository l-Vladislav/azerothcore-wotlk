-- mod-advanced-professions: именное сочетание становится РЕЦЕПТОМ.
--
-- До сих пор сочетания (ap_synergy) клиенту не показывались вовсе: игрок
-- набирал вставки вслепую, и «сложилось / не сложилось» он узнавал только на
-- завершении доводки (DESIGN §5.6, угадывание). Решение владельца 2026-09-05
-- меняет это: у профессии два рода рецептов, и оба изучаются одинаково -
--
--   рецепт основы  (ap_recipe)  - что положить в ячейки схемы, чтобы вышло
--                                 изделие;
--   именной рецепт (ap_synergy) - что вставить в готовое изделие, чтобы вышел
--                                 именной предмет.
--
-- Отсюда колонка: у сочетания появляется свой обучающий предмет, ровно как
-- `ap_recipe.teach_item`. Применение такого предмета записывает сочетание
-- изученным (acore_characters.ap_character_synergy, парная миграция), и только
-- изученные уезжают в аддон записью SYN - как и рецепты основ, которые уходят
-- на клиент только изученными.
--
-- Ноль - обучающего предмета нет. Это законное состояние: сочетание, которое
-- владелец не хочет отдавать книгой, остаётся тем, чем было, - находкой для
-- того, кто угадает набор. Завершение доводки по-прежнему сверяет набор со
-- ВСЕМИ включёнными сочетаниями, а не только с изученными: список слева - это
-- подсказка игроку, а не право на именной предмет.
--
-- Протокол при этом идёт с 12 на 13, применять вместе с пересобранным
-- worldserver и парной миграцией в pending_db_characters.

DROP PROCEDURE IF EXISTS `ap_add_column`;
DELIMITER $$
CREATE PROCEDURE `ap_add_column`(IN tbl VARCHAR(64), IN col VARCHAR(64),
                                 IN spec VARCHAR(255))
BEGIN
  IF (SELECT COUNT(*) FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = tbl
        AND COLUMN_NAME = col) = 0 THEN
    SET @s := CONCAT('ALTER TABLE `', tbl, '` ADD COLUMN `', col, '` ', spec);
    PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;
  END IF;
END$$
DELIMITER ;

CALL `ap_add_column`('ap_synergy', 'teach_item',
  'INT UNSIGNED NOT NULL DEFAULT 0 COMMENT ''entry обучающего предмета: применение записывает сочетание изученным. 0 - книги нет, сочетание только угадывается''');

DROP PROCEDURE IF EXISTS `ap_add_column`;

