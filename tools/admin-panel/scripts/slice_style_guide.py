# Порог яркости, выше которого пиксель считается содержимым, а не фоном.
# Камень листа держится в районе 20-45, кромки элементов - от 90 и выше.
INK = 72
# Сколько пикселей оставить вокруг найденного содержимого.
PAD = 1


def sheet(n):
    return os.path.join(SRC, "AdminSiteStyleGuide_%d.png" % n)


def tight_box(im, box):
    """Сжимает грубый бокс до настоящих границ элемента."""
    x0, y0, x1, y1 = box
    a = np.asarray(im.crop(box).convert("RGB")).astype(np.int16)
    ink = a.max(axis=2) >= INK
    # Одинокие яркие точки (крапины камня) в расчёт не берём: считаем строку
    # или столбец занятыми, только если ярких пикселей там хотя бы три.
    #
    # Порог именно постоянный. Пробовал считать его долей от самой плотной
    # строки - чтобы отсечь слабое свечение под кнопкой; разделители от этого
    # обрезались до нитки: у них самая плотная строка - сам прут, и на её
    # фоне наконечники порога не проходят. Полоса в шапке превратилась в 17
    # пикселей вместо 37 и поехала.
    rows = np.where(ink.sum(axis=1) >= 3)[0]
    cols = np.where(ink.sum(axis=0) >= 3)[0]
    if len(rows) == 0 or len(cols) == 0:
        return box
    return (
        max(x0, x0 + int(cols[0]) - PAD),
        max(y0, y0 + int(rows[0]) - PAD),
        min(x1, x0 + int(cols[-1]) + 1 + PAD),
        min(y1, y0 + int(rows[-1]) + 1 + PAD),
    )


def wipe_interior(im, slice_px, keep_right=0, inset=0):
    """Стирает нутро ассета, оставляя кромку.

    На листе внутри каждой кнопки и каждого поля впечатана английская
    подпись ("Primary Button", "Enter text..."), а иногда ещё значок или
    стрелка. Растянуть такую середину под свой текст нельзя - чужая надпись
    просвечивает сквозь нашу.

    Убираем её так: заливка у этих элементов - вертикальный градиент, вдоль
    строки он не меняется, а по высоте меняется ПЛАВНО. Поэтому нутро
    рисуется не построчной выборкой, а гладкой кривой: по каждой строке
    берётся медиана, а через все медианы протягивается кубика с отбраковкой
    выбросов (`fit_gradient`). Строки с подписью - как раз выбросы, и кривая
    их не замечает.

    Почему не построчный процентиль (так было раньше). У подписи на листе
    есть чёрная обводка, и она ТЕМНЕЕ заливки: нижний процентиль садился
    именно на неё, и на месте надписи оставалась тёмная полоса. Медиана без
    сглаживания мажет в другую сторону - на крупной надписи буквы занимают
    больше половины строки. Гладкой кривой не мешает ни то, ни другое: ей
    хватает строк без букв, а остальные она достраивает.

    Глубина вычистки по вертикали считается от роста ассета, а не от ширины
    кромки: у низких широких плашек (баннер, полоса заголовка) рамка тонкая,
    и `slice` там сильно больше настоящей кромки - вычисти по нему, и от
    подписи останется верх и низ букв.

    Прямоугольник вычистки - РОВНО середина девятки (от среза до среза), и
    закрашивается он до края, без растушёвки. Иначе никак: середину девятки
    браузер укладывает по всей ширине элемента (при `fill` - с тем же
    повтором, что и кромки). Оставь у её края хоть три полупрозрачных
    пикселя внутренней фаски - и на широкой кнопке они пойдут частоколом
    вертикальных полос через каждый повтор, а снизу лягут бледной лентой. На
    кнопке «Свернуть» это и было видно.

    `inset` разрешает зайти ГЛУБЖЕ среза, наружу от середины. Нужно двоим -
    смотри `DEEP`.

    `keep_right` бережёт полосу у правого края. Она нужна ровно одному ассету
    - закрытому списку: у него там нарисован уголок, и он не подпись, а
    рабочая часть. Уголок потом уезжает в ПРАВЫЙ кусок девятки (срез задан
    несимметрично), поэтому рисуется один раз и по ширине не тянется.

    Заливка так и остаётся ровной. Подмешивать в неё рельеф ЗДЕСЬ нельзя:
    середину `border-image` растягивает под размер элемента, и рисунок
    растянется вместе с ней - на узкой кнопке сожмётся, на широкой поплывёт.
    Крупинку кладёт CSS поверх, плиткой постоянного размера (`forge.scss`).
    """
    a = np.asarray(im.convert("RGB")).astype(np.float32)
    h, w = a.shape[:2]
    inset_y = min(slice_px, inset) if inset else slice_px
    x0, x1 = slice_px, w - slice_px - keep_right
    y0, y1 = inset_y, h - inset_y
    if x1 - x0 < 4 or y1 - y0 < 2:
        return im
    grad = fit_gradient(a[y0:y1, x0:x1, :])
    a[y0:y1, x0:x1, :] = grad[:, None, :]
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")


def flatten_edges(im, slice_px, keep_right=0):
    """Делает середину кромочных полос девятки однородной вдоль полосы.

    Зачем. Девятка режет ассет на девять кусков, и середина верхней полосы
    (шириной во весь ассет минус два угла) укладывается в кромку кнопки. У
    кнопки с листа этот кусок - 280 пикселей рейки с бликами и заклёпками, а
    места под него на узкой кнопке пикселей семьдесят. `round` втискивает его
    целым числом раз, то есть сплющивает втрое, `stretch` - размазывает;
    и то, и другое на экране выглядит рваной рейкой с зазубриной посередине.

    Как. Поперёк рейки рисунок нужен (это её объём), а ВДОЛЬ - нет: там
    ровный металл. Поэтому берём медиану вдоль полосы и растягиваем её на всю
    длину: профиль поперёк сохраняется до пикселя, а вдоль не остаётся
    ничего, что могло бы сплющиться или разъехаться. После этого девятке всё
    равно, какой длины кнопка.

    Ровно, как и вычистка нутра, - до самого края куска, без растушёвки: у
    растушёванного конца кусок при повторе не сходится сам с собой, и на
    каждом стыке остаётся засечка. На «Свернуть меню» во всю ширину их было
    видно с десяток.

    Углы не трогаются - в них вся нарядность (скобы, заклёпки, фаска). И
    `keep_right` бережёт правую полосу тому ассету, у которого там не рейка,
    а рабочая часть (уголок закрытого списка).
    """
    a = np.asarray(im.convert("RGB")).astype(np.float32)
    h, w = a.shape[:2]
    s = slice_px
    if w < 4 * s or h < 4 * s:
        return im

    x0, x1 = s, w - s - keep_right
    if x1 - x0 >= 8:
        for y0, y1 in ((0, s), (h - s, h)):
            band = a[y0:y1, x0:x1, :]
            a[y0:y1, x0:x1, :] = np.median(band, axis=1)[:, None, :]

    y0, y1 = s, h - s
    if y1 - y0 >= 8:
        for xa, xb in ((0, s), (w - s - keep_right, w - keep_right)):
            band = a[y0:y1, xa:xb, :]
            a[y0:y1, xa:xb, :] = np.median(band, axis=0)[None, :, :]

    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")


def fit_gradient(band, deg=3):
    """Гладкий вертикальный градиент заливки по куску картинки.

    Берёт медиану каждой строки и протягивает через них многочлен, на каждом
    проходе выбрасывая строки, далеко отошедшие от кривой. Выбросы - это
    строки с подписью или значком; после двух-трёх проходов остаётся чистая
    заливка, а кривая отдаёт её цвет и для выброшенных строк тоже.
    """
    med = np.median(band, axis=1)
    n = med.shape[0]
    if n < deg + 2:
        return np.repeat(np.median(med, axis=0)[None, :], n, axis=0)
    t = np.linspace(-1.0, 1.0, n)
    # Крайние строки полосы в подгонку не берём. Прямоугольник вычистки
    # считается по срезу девятки, а он не обязан совпадать с настоящей
    # толщиной кромки: у кнопки «Свернуть» рамка толще среза, и в полосу
    # попадали две-три строки её внутренней фаски. Кривая тянулась к ним, и
    # фаска, светлая только у самого канта, размазывалась ровной светлой
    # линией во всю ширину нутра.
    edge = max(2, n // 7)
    body = np.zeros(n, dtype=bool)
    body[edge : n - edge] = True
    if body.sum() < deg + 2:
        body[:] = True
    out = np.empty_like(med)
    for c in range(3):
        v = med[:, c]
        keep = body.copy()
        k = np.polyfit(t[keep], v[keep], deg)
        for _ in range(3):
            resid = np.abs(v - np.polyval(k, t))
            # Порог от медианного отклонения: у ровной заливки он копеечный,
            # и строки с буквами вылетают сразу, а плавный изгиб остаётся.
            nxt = body & (resid <= np.median(resid[keep]) * 2.0 + 0.75)
            if nxt.sum() < deg + 2 or (nxt == keep).all():
                break
            keep = nxt
            k = np.polyfit(t[keep], v[keep], deg)
        # За пределами подогнанных строк многочлен волен уйти куда угодно -
        # держим его в тех же берегах, что и сама заливка.
        lo, hi = v[keep].min(), v[keep].max()
        out[:, c] = np.clip(np.polyval(k, t), lo, hi)
    return np.clip(out, 0, 255)


def _spans(bright, grow):
    """Первый и последний яркий индекс вдоль оси 0, сглаженные по оси 1."""
    n, m = bright.shape
    any_b = bright.any(axis=0)
    first = np.where(any_b, np.argmax(bright, axis=0), n)
    last = np.where(any_b, n - 1 - np.argmax(bright[::-1], axis=0), -1)
    # Сглаживание вдоль второй оси: без него край получается зубчатым - там,
    # где в столбце случайно не нашлось яркой точки, силуэт проваливается.
    pad = 2
    first = np.array([first[max(0, i - pad) : i + pad + 1].min() for i in range(m)])
    last = np.array([last[max(0, i - pad) : i + pad + 1].max() for i in range(m)])
    # «Занято» тоже считаем по окну, а не по одному столбцу. У бледных
    # элементов (погашенная кнопка) кромка местами не дотягивает до порога, и
    # строгая проверка вырезала из них сквозные прозрачные просветы.
    any_b = np.array([any_b[max(0, i - pad) : i + pad + 1].any() for i in range(m)])
    return any_b, first - grow, last + grow


def cut_to_contour(im, thresh=60, grow=2):
    """Срезает фон листа снаружи элемента, оставляя его силуэт.

    Зачем. Всё на листах нарисовано на тёмном камне, и грубый бокс режет
    вместе с ним: у скруглённой кнопки - чёрные уголки, у огонька состояния -
    чёрный квадрат вокруг кружка, у разделителя - кайма сверху и снизу.
    Пока фон страницы был тем же камнем, это сходило за фон; на панели,
    в шапке или на своей заливке каждый элемент садится в чужой тёмный
    прямоугольник.

    Как. Порогом по яркости ищем кромку (она у всех светлая - золото, сталь,
    цветная эмаль) и СТОЛБЕЦ ЗА СТОЛБЦОМ оставляем непрозрачным всё между
    верхним и нижним ярким пикселем. Столбец сам по себе знает и скруглённый
    угол (у края элемента кромка начинается ниже, чем в середине), и круглый
    огонёк, и разделитель с его пустотой сверху и снизу.

    Почему только по столбцам. Пробовал добавить второй голос - строчный
    промежуток. Строгое пересечение двух голосов сносило бока у элементов с
    тусклой боковой кромкой: у полосы заголовка раздела бок темнее порога,
    первым ярким в строке оказывался узор на другом её конце, и всё левее
    уходило в прозрачность. Объединение ломало разделители: у них по краям
    высокие наконечники, и строка на их высоте тянулась от одного до другого
    - между ними оставалась во всю ширину тёмная полоса пустого камня.
    Столбец в одиночку не ошибается ни там, ни там.

    Нутро при этом целое, пусть оно и темнее порога: его закрывает кромка,
    то есть по своему столбцу оно лежит МЕЖДУ яркими пикселями. По той же
    причине сохраняются тёмные обводки внутри рисунка, а они и делают
    металл металлом.

    `grow` - на сколько пикселей отпустить силуэт наружу, чтобы не срезать
    полупрозрачный край самой кромки.
    """
    rgb = np.asarray(im.convert("RGB"))
    a = rgb.astype(np.int16)
    h, w = a.shape[:2]
    bright = a.max(axis=2) >= thresh
    if not bright.any():
        return im.convert("RGBA")

    col_any, top, bottom = _spans(bright, grow)

    ys = np.arange(h)[:, None]
    keep = col_any[None, :] & (ys >= top[None, :]) & (ys <= bottom[None, :])
    alpha = np.where(keep, 255, 0).astype(np.uint8)
    # Край силуэта сглаживаем: ступенька из чистых нулей и двухсот пятидесяти
    # пяти на скруглении видна лесенкой.
    alpha = np.asarray(Image.fromarray(alpha).filter(ImageFilter.GaussianBlur(0.6)))
    was = np.asarray(im.convert("RGBA"))[:, :, 3]
    alpha = np.minimum(alpha, was).astype(np.uint8)
    return Image.fromarray(np.dstack([rgb, alpha]), "RGBA")


def square_edges(im, slice_px, slack=6):
    """Доводит грань до края у ассетов, нарисованных прямоугольником.

    Зачем. Силуэт `cut_to_contour` ведёт СТОЛБЦОМ, по яркой кромке. Свет на
    листах падает сверху, поэтому наружная обводка снизу тёмная: сверху и с
    боков она 40-70 по яркости и порог проходит, а снизу 16-21 и не
    проходит. В углах та же обводка подсвечена и остаётся. Выходит, что низ
    ассета кончается в середине на два-пять пикселей выше, чем в углах,
    габарит задают углы - и в нижней полосе девятки середина короче полосы.
    На экране рейка по низу висит над краем кнопки, а пятки углов достают до
    него: кнопка выглядит криво срезанной.

    Как. Обводка НИКУДА не делась - у этих пикселей просто обнулили альфу,
    цвет на месте. Поэтому не режем, а возвращаем: по середине каждой
    стороны достраиваем силуэт до той же грани, до какой он доходит в
    остальных столбцах. Грань берём по медиане, чтобы одинокий выброс её не
    утянул. Глубже `slack` не достраиваем - иначе ассету, у которого
    середина стороны пуста по замыслу, пририсуется фон листа.

    Углы не трогаются: там силуэт и так доходит до края, а внутрь от них
    идёт скругление, которому квадратная грань ни к чему.

    Годится только тем, у кого силуэт - честный прямоугольник (`SQUARE`): у
    подсказки снизу хвостик, у разделителя наконечники, у огонька круг.
    """
    a = np.array(im.convert("RGBA"))
    solid = a[:, :, 3] > 8
    h, w = solid.shape
    s = max(4, min(slice_px or 16, h // 3, w // 3))
    changed = False

    def level(strip, depth):
        """Докрашивает в полосе всё до `depth`-го ряда от края.

        `strip` - вид на альфу, у которого первая ось идёт ОТ КРАЯ внутрь,
        вторая - вдоль стороны. Пишем прямо в него: это срез исходного
        массива, а не копия.
        """
        for k in range(strip.shape[1]):
            line = strip[:, k] > 8
            if line.any() and 0 < int(np.argmax(line)) <= depth:
                strip[: int(np.argmax(line)), k] = 255

    def gap(strip):
        """Медиана пустых рядов у края по середине стороны."""
        runs = [int(np.argmax(c)) for c in (strip > 8).T if c.any()]
        return min(int(np.median(runs)), slack) if runs else 0

    for strip in (
        a[:, s:w - s, 3],            # верх
        a[::-1, s:w - s, 3],         # низ
        a[s:h - s, :, 3].T,          # левый борт
        a[s:h - s, ::-1, 3].T,       # правый борт
    ):
        depth = gap(strip)
        if depth:
            level(strip, depth)
            changed = True

    return Image.fromarray(a, "RGBA") if changed else im


def tint(im, rgb, gamma=0.68):
    """Перекрашивает кромку в заданный цвет, сохраняя рельеф.

    Зачем. Карточка доски показывает приоритет цветом ОБВОДКИ, и это должна
    быть та же кованая кромка, только в цвете. Крутить её на лету фильтрами
    (`sepia` + `hue-rotate`) - гадание: попасть в конкретный #ff2020 так
    нельзя, оттенок получается какой выйдет. Проще покрасить саму картинку
    один раз здесь.

    Как. Берём яркость пикселя и умножаем на цвет: рельеф, заклёпки и фаска
    остаются, а тон становится ровно заданным. `gamma` чуть поднимает средние
    тона (0.68 подобрано на глаз по карточкам доски) - иначе тёмная кромка
    в цвете выглядит грязным пятном. Прозрачность
    не трогаем.
    """
    rgba = np.asarray(im.convert("RGBA")).astype(np.float32)
    lum = rgba[:, :, :3].max(axis=2) / 255.0
    shade = np.power(lum, gamma)
    out = rgba.copy()
    for i, channel in enumerate(rgb):
        out[:, :, i] = shade * channel
    return Image.fromarray(np.clip(out, 0, 255).astype(np.uint8), "RGBA")


def hollow_ring(im, slice_px, rim=0, feather=1.0):
    """Гасит всё, что лежит ВНУТРИ кромочной полосы девятки.

    Зачем. Ассет рамки едет к пользователю целиком, а браузер рисует из него
    только полосу по краю: без `fill` середины у `border-image` нет вовсе. У
    сетки таблицы середина - это пять нарисованных строк с именами, и весила
    она больше полумегабайта - впустую.

    Почему не `cut_frame_interior`: тот ищет металл порогом по яркости и
    держится на тёмном нутре панели. Строки таблицы ярче прута, и порог
    оставляет их на месте.

    Как. Искать нечего: ширина полосы известна заранее - это тот же `slice`,
    который уйдёт в CSS. Всё строго внутри неё гасим, край растушёвываем на
    пиксель, чтобы не осталось ступеньки.
    """
    rgba = np.asarray(im.convert("RGBA")).copy()
    h, w = rgba.shape[:2]
    if h <= 2 * slice_px or w <= 2 * slice_px:
        return Image.fromarray(rgba, "RGBA")
    # `rim` - сколько пикселей ЧЕРНИЛ оставить вдоль стороны. У сетки таблицы
    # рейка тонкая (четыре пикселя), а срез широкий (тридцать шесть - столько
    # занимает угловая скоба), и всё, что между ними, - кусок шапки листа. Без
    # `rim` он остаётся в полосе, и кромку, нарисованную в полный рост
    # (`border-image-width`), было бы видно тёмной каймой поверх таблицы. Углы
    # при этом не трогаем: там живёт сама скоба.
    keep = rim or slice_px
    inner = np.zeros((h, w), np.uint8)
    inner[keep : h - keep, keep : w - keep] = 255
    if rim:
        corners = np.zeros((h, w), bool)
        corners[:slice_px, :slice_px] = True
        corners[:slice_px, w - slice_px :] = True
        corners[h - slice_px :, :slice_px] = True
        corners[h - slice_px :, w - slice_px :] = True
        inner[corners] = 0
        # В углу оставляем только сами чернила - скобу и рейку. Остальное там
        # - клок шапки листа, и в полный рост (`border-image-width`) он лёг бы
        # тёмным квадратом поверх угла таблицы.
        dark = np.asarray(im.convert("RGB")).max(axis=2) < INK
        inner[corners & dark] = 255
    if feather:
        inner = np.asarray(
            Image.fromarray(inner).filter(ImageFilter.GaussianBlur(feather)))
    rgba[:, :, 3] = np.minimum(rgba[:, :, 3], 255 - inner).astype(np.uint8)
    # И сами цвета под прозрачным гасим. PNG хранит цвет даже там, где альфа
    # ноль, и невидимые строки таблицы жали файл до полумегабайта; ровное
    # чёрное поле ужимается почти в ничто.
    rgba[:, :, :3][rgba[:, :, 3] == 0] = 0
    return Image.fromarray(rgba, "RGBA")


def cut_frame_interior(im, slice_px, close_r=6, open_r=2):
    """Оставляет от рамки-кольца только сам металл, всё прочее - насквозь.

    Зачем. Рамки панелей идут в `border-image` БЕЗ `fill`: середину им даёт
    фон страницы. Но прут у них тонкий - у `panel-thin` пикселей семь, - а
    вырезаны они вместе с широким куском тёмно-синего нутра листа. При кромке
    в 26 пикселей это нутро занимает три четверти кромочной полосы девятки,
    и на панели своего цвета читается каймой чужого оттенка по всему
    периметру. Снаружи та же беда с тенью.

    Как. Порогом по яркости берём сам металл, а дальше две операции подряд.
    СМЫКАНИЕ (наращивание и сжатие на тот же радиус) затягивает дыры в пруте:
    внутри него идут тёмные линии фаски и промежутки между заклёпками, по
    порогу они не проходят, и без смыкания прут выходил бы дырявым. ОТКРЫТИЕ
    (сжатие и наращивание) убирает одинокие искры - крапины камня, попавшие
    выше порога. Нутро и тень шире радиуса во много раз и остаются снаружи.

    Порог считается по самой картинке, а не берётся общий: у `panel-inset`
    камень внутри вдвое светлее, чем у `panel-thin`, и общий порог либо
    оставлял бы в нём кляксы, либо ронял бы прут у тёмных рамок. Берём почти
    максимум яркости нутра (центральная четверть) с запасом.
    """
    rgb = np.asarray(im.convert("RGB"))
    m = rgb.astype(np.int16).max(axis=2)
    h, w = m.shape
    core = m[h // 4 : 3 * h // 4, w // 4 : 3 * w // 4]
    thr = int(np.clip(np.percentile(core, 99) + 10, 45, 90))

    bright = (m >= thr).astype(np.uint8) * 255
    # Прозрачная кайма вокруг маски на время операций. Без неё сжатие у самой
    # границы картинки некуда стягивать (фильтр там продолжает крайний
    # пиксель), и наращивание остаётся несжатым: над верхней рейкой и под
    # нижней в ассете оставалась чёрная полоса фона листа в пару пикселей. На
    # панели она читалась тёмной каймой сверху и снизу - по бокам та же
    # полоса вертикальная и в глаза не бросалась.
    pad = close_r + open_r + 1
    mask = Image.fromarray(np.pad(bright, pad), "L")
    size = 2 * close_r + 1
    mask = mask.filter(ImageFilter.MaxFilter(size)).filter(ImageFilter.MinFilter(size))
    size = 2 * open_r + 1
    mask = mask.filter(ImageFilter.MinFilter(size)).filter(ImageFilter.MaxFilter(size))
    soft = np.asarray(mask.filter(ImageFilter.GaussianBlur(0.8))).astype(np.float32)
    # Размытие даёт мягкий край, но заодно приоткрывает пиксель фона снаружи
    # рейки, а он чёрный - и снова выходит тёмная ниточка по верху и низу.
    # Поэтому слабую часть шлейфа срезаем: край остаётся сглаженным, но
    # начинается ровно на металле.
    soft = np.clip((soft - 80.0) * (255.0 / 175.0), 0, 255).astype(np.uint8)
    alpha = soft[pad:-pad, pad:-pad]
    return Image.fromarray(np.dstack([rgb, alpha]), "RGBA")


def trim_alpha(im, slack=4):
    """Обрезает прозрачные поля по краям - до самой рейки.

    После того как от рамки-кольца остаётся один металл, снаружи у неё висит
    по паре прозрачных строк и столбцов - бывший фон листа. Сами по себе они
    пусты, но `border-image` кладёт их в кромочную полосу девятки, а фон
    панели рисуется под всей рамкой (`background-clip` по умолчанию -
    `border-box`). Значит, сквозь них видно не страницу, а тёмную заливку
    самой панели, и по верху и низу идёт тёмная ниточка.

    Режем не по общему габариту, а по СЕРЕДИНЕ стороны: уголки у рамок часто
    выступают наружу на пиксель-другой, и по габариту рейка в середине всё
    равно осталась бы не с нулевой строки. Уголку от этого не убудет - глубже
    `slack` пикселей за габарит не заходим.
    """
    a = np.asarray(im.convert("RGBA"))
    solid = a[:, :, 3] > 8
    ys, xs = np.where(solid)
    if not len(ys):
        return im
    box = [int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1]

    def edge(line, lo, hi, reverse=False):
        """Сколько пустых рядов у края, если смотреть по середине стороны."""
        idx = range(len(line) - 1, -1, -1) if reverse else range(len(line))
        for k, i in enumerate(idx):
            if line[i]:
                return k
        return 0

    h, w = solid.shape
    cx0, cx1 = int(w * 0.2), int(w * 0.8)
    cy0, cy1 = int(h * 0.2), int(h * 0.8)
    mid_rows = solid[:, cx0:cx1].mean(axis=1) > 0.5
    mid_cols = solid[cy0:cy1, :].mean(axis=0) > 0.5
    box[1] = min(box[1] + slack, max(box[1], edge(mid_rows, cy0, cy1)))
    box[3] = max(box[3] - slack, min(box[3], h - edge(mid_rows, cy0, cy1, True)))
    box[0] = min(box[0] + slack, max(box[0], edge(mid_cols, cx0, cx1)))
    box[2] = max(box[2] - slack, min(box[2], w - edge(mid_cols, cx0, cx1, True)))
    if box[2] - box[0] < 8 or box[3] - box[1] < 8:
        return im
    return im.crop(tuple(box))


def seam_edges(im, slice_px, fade=14):
    """Сводит концы кромочных кусков девятки, чтобы повтор не оставлял шва.

    Зачем. У нарядных рамок рейка с рисунком - заклёпки, накладки, - и её
    `round` укладывает вдоль панели несколько раз. Рисунок на левом конце
    куска не продолжает правый, и на каждом стыке видна засечка: на толстой
    панели это четыре-пять разрывов по верхней рейке.

    Как. Хвост куска плавно сводится к его же голове: на последних `fade`
    пикселях подмешиваем то, что пойдёт следом при повторе. После этого конец
    куска переходит в его начало без ступеньки. Сам рисунок в середине не
    трогаем - заклёпки остаются заклёпками.

    Углы девятки не повторяются, их это не касается.
    """
    a = np.asarray(im.convert("RGBA")).astype(np.float32)
    h, w = a.shape[:2]
    s = slice_px

    def blend(piece):
        n = piece.shape[0]
        f = min(fade, n // 3)
        if f < 2:
            return piece
        t = ((np.arange(f) + 1) / (f + 1.0)).astype(np.float32)
        shape = (f,) + (1,) * (piece.ndim - 1)
        t = t.reshape(shape)
        piece[n - f :] = piece[n - f :] * (1 - t) + piece[:f] * t
        return piece

    if w - 2 * s >= 12:
        for y0, y1 in ((0, s), (h - s, h)):
            a[y0:y1, s : w - s] = blend(a[y0:y1, s : w - s].transpose(1, 0, 2)).transpose(1, 0, 2)
    if h - 2 * s >= 12:
        for x0, x1 in ((0, s), (w - s, w)):
            a[s : h - s, x0:x1] = blend(a[s : h - s, x0:x1])

    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGBA")


def wipe_grip(im):
    """Стирает уголок-ползунок в правом нижнем углу поля ввода.

    На листе у многострочного поля нарисован «уголок для растягивания» - три
    косые чёрточки. Браузер рисует свой такой же поверх, и получается два
    уголка. Хуже того, уголок с листа не помещается в угловой кусок девятки и
    попадает в НИЖНЮЮ полосу - а она повторяется, и уголок идёт частоколом
    вдоль всего низа.

    Нижняя кромка вдоль строки одинаковая, поэтому уголок просто закрывается
    куском той же кромки левее.
    """
    a = np.asarray(im.convert("RGB")).copy()
    h, w = a.shape[:2]
    if w < 140 or h < 60:
        return im
    # Рамка снаружи не трогается - берём только то, что внутри неё.
    y0, y1 = h - 26, h - 4
    x0, x1 = w - 34, w - 4
    a[y0:y1, x0:x1] = a[y0:y1, x0 - 40 : x1 - 40]
    return Image.fromarray(a, "RGB")


def gold_run(a):
    """Левый край самой длинной сплошной золотой полосы по столбцам."""
    h = a.shape[0]
    mid = a[int(h * 0.35) : int(h * 0.65)]
    g = (mid[:, :, 0] > 120) & (mid[:, :, 0] - mid[:, :, 2] > 60)
    col = g.mean(axis=0) > 0.8
    best = (0, 0)
    start = None
    for x, on in enumerate(np.append(col, False)):
        if on and start is None:
            start = x
        elif not on and start is not None:
            if x - start > best[0]:
                best = (x - start, start)
            start = None
    return best[1] if best[0] > 8 else 0


def empty_track(im, slice_px):
    """Опустошает жёлоб шкалы: с листа она снята налитой на 68%.

    Золото с листа в ассете не нужно и вредно. Шкала идёт в девятку, и доля
    у неё своя на каждый случай: кромочные полосы повторяются, и запечённое
    золото вылезало бы в них куском налитой шкалы независимо от доли, а на
    стыке - обрывом посередине. Наливает шкалу CSS (`.forge-progress > i`),
    ассету остаётся пустой жёлоб.

    Пустой конец у шкалы на листе есть - он справа, за границей налитого.
    Оттуда и берём столбец: по строкам, потому что поперёк шкалы идёт и
    жёлоб, и стальные рейки сверху и снизу, и подхватить их надо заодно -
    золото подсвечивает рейку и вылезает искрами за рамку.

    Поэтому середина шкалы (всё, кроме золотых уголков по краям) целиком
    перерисовывается этим столбцом, на всю высоту, а не только внутри рамки.
    """
    a = np.asarray(im.convert("RGB")).astype(np.float32)
    h, w = a.shape[:2]
    # Уголки по краям - часть рамки, их бережём. Где кончается уголок и
    # начинается налитое, ищем по самой длинной сплошной золотой полосе: у
    # уголка золото тоже во всю высоту, но шириной в пару пикселей, а у
    # налитого - на сотни. Брать `slice_px` на глаз нельзя: между уголком и
    # началом налитого пара пикселей, и промах виден золотым огрызком.
    x0 = gold_run(a) or slice_px
    x1 = w - x0
    # Пустой участок: между концом налитого (около 68%) и правым уголком.
    sx0, sx1 = int(w * 0.80), int(w * 0.93)
    if x1 - x0 < 8 or sx1 - sx0 < 4:
        return im
    col = np.median(a[:, sx0:sx1, :], axis=1)
    patch = np.broadcast_to(col[:, None, :], (h, x1 - x0, 3))
    # Растушёвка только поперёк: по высоте врезка идёт до самого края.
    n = x1 - x0
    rx = np.clip((np.minimum(np.arange(n), n - 1 - np.arange(n)) + 1) / 3.0, 0, 1)
    m = rx.astype(np.float32)[None, :, None]
    a[:, x0:x1, :] = a[:, x0:x1, :] * (1 - m) + patch * m
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")


