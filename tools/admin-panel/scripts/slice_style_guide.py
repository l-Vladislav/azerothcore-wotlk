# --- фоновые текстуры ----------------------------------------------------
#
# (файл-источник, имя плитки, сторона плитки в пикселях)
# Листы `AdminSiteStyleGuideBackground_*.png` - это РЕНДЕРЫ, а не плитки:
# положи такой фон в `repeat`, и по стыкам пойдут швы. `seamless_tile` ниже
# делает из куска рендера плитку, которая стыкуется сама с собой.

BACKGROUNDS = [
    (1, "stone-dark", 768),
    (2, "stone-carved", 768),
    (3, "stone-fine", 768),
    (4, "slate", 768),
]


def background(n):
    return os.path.join(SRC, "AdminSiteStyleGuideBackground_%d.png" % n)


def seamless_tile(im, side, feather=96):
    """Делает из куска рендера плитку без швов.

    Идея: чтобы плитка стыковалась, левый столбец обязан совпадать с правым,
    а верхняя строка - с нижней. Добиваемся этого подмешиванием зеркальной
    копии, но ТОЛЬКО в узкой полосе у краёв: у самого края доли ровно по
    половине, и слева получается то же, что справа, а к середине примесь
    сходит на нет.

    Почему не смешивать по всей ширине (так было сначала): тогда вся плитка
    становится симметричной, и на странице это читается калейдоскопом -
    бабочками по стыкам. При узкой полосе симметрия остаётся у кромки, где
    она выглядит как обычный камень, а середина - нетронутый рендер.
    """
    w, h = im.size
    side = min(side, w, h)
    left, top = (w - side) // 2, (h - side) // 2
    a = np.asarray(im.crop((left, top, left + side, top + side)).convert("RGB")).astype(np.float32)

    feather = min(feather, side // 4)
    x = np.arange(side, dtype=np.float32)
    # Доля зеркала: 0.5 у самой кромки, ноль дальше `feather` от неё.
    wx = np.maximum(0.0, 0.5 * (1.0 - np.minimum(x, side - 1 - x) / feather))

    mix = a * (1 - wx)[None, :, None] + a[:, ::-1, :] * wx[None, :, None]
    mix = mix * (1 - wx)[:, None, None] + mix[::-1, :, :] * wx[:, None, None]
    return Image.fromarray(np.clip(mix, 0, 255).astype(np.uint8), "RGB")


def make_backgrounds():
    """Кладёт плитки в `public/ui/textures/`. JPEG, а не PNG: они непрозрачные
    и шумные, PNG на таком раздувается в полмегабайта на штуку."""
    d = os.path.join(OUT, "textures")
    os.makedirs(d, exist_ok=True)
    done = []
    for n, name, side in BACKGROUNDS:
        path = background(n)
        if not os.path.exists(path):
            continue
        tile = seamless_tile(Image.open(path), side)
        out = os.path.join(d, name + ".jpg")
        tile.save(out, quality=88, optimize=True)
        done.append((name, os.path.getsize(out) // 1024))
    return done


def contact_sheet(made, cols=6, cell=240):
    """Лист для глазной проверки: всё нарезанное в клетках с подписями."""
    rows = (len(made) + cols - 1) // cols
    sh = Image.new("RGB", (cols * cell, rows * (cell + 18)), (16, 16, 18))
    d = ImageDraw.Draw(sh)
    for i, (name, im) in enumerate(made):
        cx, cy = (i % cols) * cell, (i // cols) * (cell + 18)
        t = im.copy()
        t.thumbnail((cell - 8, cell - 8))
        sh.paste(t, (cx + (cell - t.width) // 2, cy + (cell - t.height) // 2))
        d.text(
            (cx + 4, cy + cell + 2),
            "%s %dx%d" % (name, im.width, im.height),
            fill=(200, 190, 150),
        )
        d.rectangle([cx, cy, cx + cell - 1, cy + cell + 16], outline=(60, 58, 52))
    sh.save(os.path.join(HERE, "style-guide-contact-sheet.png"))


