#!/usr/bin/env python3
"""Режет листы стайлгайда (AdminSiteStyleGuide_*.png) на отдельные ассеты.

Зачем скриптом, а не руками в рисовалке: листы - это рендеры, и резать их
придётся ещё не раз (пришлют новый лист, поправят цвет, добавят состояние).
Ручная нарезка каждый раз начинается сначала, а тут вся правка - это строка
в таблице ниже.

Как это работает. Для каждого ассета задан ГРУБЫЙ прямоугольник - снятый с
координатной сетки на глаз. Точную границу ищет `tight_box`: у всех элементов
листа кромка светлая (золото, сталь, цветная эмаль), а фон - тёмный камень,
поэтому достаточно взять рамку ярких пикселей. Значит, боксы ниже можно
задавать с запасом - лишь бы в них не попала соседняя подпись.

Дальше каждый вырезанный кусок обрезается ПО КОНТУРУ (`cut_to_contour`):
камень листа снаружи элемента уходит в прозрачность. Иначе скруглённая
кнопка везёт с собой чёрные уголки, а круглый огонёк - чёрный квадрат.

Что получается в `frontend/public/ui/`:

  * `frames/`, `buttons/`, `nav/`, `tabs/` - заготовки под `border-image`
    (девятка). Середина у них непрозрачная, и это нормально: без ключевого
    слова `fill` браузер середину не рисует.
  * `dividers/` - разделители, растягиваются по горизонтали (тройка).
  * `icons/`, `status/`, `forms/`, `brand/` - штучные картинки.

Рядом с ассетами кладётся `manifest.json` (размеры и рекомендуемый `slice`
для девяток), а контактный лист для глазной проверки - в `scripts/`: он
весит под два мегабайта и в `public/` ему делать нечего, оттуда всё уезжает
в браузер.

Запуск (нужен Pillow + numpy; в контейнере панели их нет - гоняем локально):

    python tools/admin-panel/scripts/slice_style_guide.py [папка-с-листами]
"""

